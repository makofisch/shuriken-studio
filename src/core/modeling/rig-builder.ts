import { existsSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { jointOrder, type RigSpec } from '@shared/rig';
import { ModelStore, NORMALS_FN, PLACE_FN, meshNormals, type ModelMeta } from './model-store';

export const RIGS_BUILDER_REL = 'world/Rigs.luau';

/**
 * world/Rigs.luau: every rigged model whose parts are uploaded becomes a template under
 * ReplicatedStorage.ShurikenRigs, ready to clone and animate:
 * - a HumanoidRootPart at the root joint's pivot (anchored, invisible; the model's PrimaryPart),
 * - one invisible part per segment at its joint's pivot, named like the joint (what a KeyframeSequence's
 *   Poses are named), joined to its parent's by a Motor6D whose C0/C1 are axis-aligned at rest — so a
 *   Pose's CFrame is the clip's rotation about the pivot, as @shared/rig computes it,
 * - the model's MeshParts (one per segment and material) welded to their segment, massless and
 *   non-colliding (raycasts and hitboxes still see them),
 * - an AnimationController with its Animator (Anims.play(model, clip) plays on it),
 * - the rig's attachment points (grips, muzzles, sockets) as Attachments on their segments.
 * Idempotent, like every world builder.
 *
 * A part takes its mesh from its uploaded asset (`assets`) or, for a part that isn't uploaded (yet) or
 * whose asset Studio can't load yet, from a temporary mesh staged under ShurikenRigs._Staging
 * (`temporary`, see stageMeshesLuau): a rig is built from what is there, the rest staged. With
 * `skipMissing` a part that has neither is left out (and reported in `skipped`) instead of failing the
 * whole rig, so one missing part never leaves a stale older build in the place. `known` lists every
 * rig of the project: templates of rigs not in it are removed (default: the rigs given).
 */
export function rigsBuilder(rigs: Array<{ rig: RigSpec; parts: ModelMeta[]; assets: Record<string, string> }>, opts: { temporary?: boolean; skipMissing?: boolean; known?: string[] } = {}): string {
  const n = (v: number) => String(Math.round(v * 1e4) / 1e4);
  const v3 = (v: readonly number[]) => `{${v.map(n).join(',')}}`;
  const rows = rigs.map(({ rig, parts, assets }) => {
    const joints = jointOrder(rig)
      .map((j) => `{name=${JSON.stringify(j.name)},parent=${j.parent ? JSON.stringify(j.parent) : 'nil'},pivot=${v3(j.pivot)}}`)
      .join(',');
    const meshes = parts
      .map((p) => `{name=${JSON.stringify(p.name)},asset=${assets[p.name] ?? 'nil'},segment=${JSON.stringify(p.segment ?? rig.root)},origin=${v3(p.origin ?? [0, 0, 0])},size=${v3(p.size)}${p.color ? `,color=${JSON.stringify(p.color)}` : ''}${p.material ? `,material=${JSON.stringify(p.material)}` : ''}${p.transparency ? `,transparency=${n(p.transparency)}` : ''}${assets[p.name] && ModelStore.legacyUpload(p) ? ',turn=true' : ''}}`)
      .join(',');
    const attachments = rig.attachments.map((a) => `{name=${JSON.stringify(a.name)},part=${JSON.stringify(a.part)},position=${v3(a.position)}}`).join(',');
    return `  {name=${JSON.stringify(rig.model)},root=${JSON.stringify(rig.root)},joints={${joints}},parts={${meshes}},attachments={${attachments}}},`;
  });
  return `-- Generated by Shuriken Studio from models/*.rig.json. Do not edit: rebuild with rig_build.
local ReplicatedStorage = game:GetService("ReplicatedStorage")
local InsertService = game:GetService("InsertService")
local HttpService = game:GetService("HttpService")
local RIGS = {
${rows.join('\n')}
}
-- Parts that aren't uploaded (or whose asset can't be loaded yet) were staged as temporary meshes.
local TEMPORARY = ${opts.temporary ? 'true' : 'false'}
-- A part with no mesh at all is left out of the rig (and reported) instead of failing it.
local SKIP_MISSING = ${opts.skipMissing ? 'true' : 'false'}
local KNOWN = {${(opts.known ?? rigs.map((r) => r.rig.model)).map((k) => `[${JSON.stringify(k)}]=true`).join(',')}}
${PLACE_FN}
local folder = ReplicatedStorage:FindFirstChild("ShurikenRigs")
if not folder then
  folder = Instance.new("Folder")
  folder.Name = "ShurikenRigs"
  folder.Parent = ReplicatedStorage
end
local function v(t) return Vector3.new(t[1], t[2], t[3]) end
local function build(r)
  local model = Instance.new("Model")
  model.Name = r.name
  local rootPivot = nil
  for _, j in r.joints do
    if j.name == r.root then rootPivot = v(j.pivot) end
  end
  local hrp = Instance.new("Part")
  hrp.Name = "HumanoidRootPart"
  hrp.Size = Vector3.new(1, 1, 1)
  hrp.Transparency = 1
  hrp.CanCollide = false
  hrp.Anchored = true
  hrp.CFrame = CFrame.new(rootPivot or Vector3.zero)
  hrp.Parent = model
  model.PrimaryPart = hrp
  local seg = {}
  for _, j in r.joints do
    local s = Instance.new("Part")
    s.Name = j.name
    s.Size = Vector3.new(0.2, 0.2, 0.2)
    s.Transparency = 1
    s.CanCollide = false
    s.CanQuery = false
    s.CanTouch = false
    s.Massless = true
    s.CFrame = CFrame.new(v(j.pivot))
    s.Parent = model
    seg[j.name] = s
  end
  for _, j in r.joints do
    local parentPart = if j.parent then seg[j.parent] else hrp
    local m = Instance.new("Motor6D")
    m.Name = j.name
    m.Part0 = parentPart
    m.Part1 = seg[j.name]
    m.C0 = parentPart.CFrame:ToObjectSpace(CFrame.new(v(j.pivot)))
    m.C1 = CFrame.new()
    m.Parent = parentPart
  end
  local staged = if TEMPORARY then folder:FindFirstChild("_Staging") and folder._Staging:FindFirstChild(r.name) else nil
  local skipped = {}
  for _, p in r.parts do
    local src = nil
    local why = nil
    local fromAsset = false
    if p.asset then
      local ok, got = pcall(meshOf, p.asset)
      if ok then
        src = got
        fromAsset = true
      else
        why = tostring(got)
      end
    end
    if not src and staged then src = staged:FindFirstChild(p.name) end
    if not src then
      if not SKIP_MISSING then error("no mesh for " .. p.name .. " (" .. (why or (if TEMPORARY then "not staged" else "not uploaded")) .. ")") end
      table.insert(skipped, { rig = r.name, name = p.name, why = why or "no mesh" })
      continue
    end
    local mp = src:Clone()
    mp.Name = p.name
    mp.Size = v(p.size)
    mp.CFrame = CFrame.new(v(p.origin))
    -- A legacy upload (made before the importer's 180° turn was compensated, see glb.ts) arrives turned about
    -- its own centre: turned back here, so the weld to its segment keeps it. Marked uploads and staged meshes need nothing.
    if p.turn and fromAsset then mp.CFrame = mp.CFrame * CFrame.Angles(0, math.pi, 0) end
    if p.color then mp.Color = Color3.fromHex(p.color) end
    if p.material then mp.Material = Enum.Material[p.material] end
    if p.transparency then mp.Transparency = p.transparency end
    mp.Anchored = false
    mp.CanCollide = false
    mp.Massless = true
    mp:SetAttribute("ShurikenModel", p.name)
    local w = Instance.new("WeldConstraint")
    w.Part0 = seg[p.segment] or hrp
    w.Part1 = mp
    w.Parent = mp
    mp.Parent = model
  end
  for _, a in r.attachments do
    local host = seg[a.part] or hrp
    local att = Instance.new("Attachment")
    att.Name = a.name
    att.Position = host.CFrame:PointToObjectSpace(v(a.position))
    att.Parent = host
  end
  local ac = Instance.new("AnimationController")
  ac.Parent = model
  Instance.new("Animator").Parent = ac
  model:SetAttribute("ShurikenRig", r.name)
  if TEMPORARY then model:SetAttribute("ShurikenTemporaryMesh", true) end
  return model, skipped
end
local built, failed, skippedParts = {}, {}, {}
for _, r in RIGS do
  local ok, result, skipped = pcall(build, r)
  if ok then
    local old = folder:FindFirstChild(r.name)
    if old then old:Destroy() end
    result.Parent = folder
    table.insert(built, r.name)
    for _, s in skipped do table.insert(skippedParts, s) end
  else
    table.insert(failed, { name = r.name, error = tostring(result) })
  end
  local stage = folder:FindFirstChild("_Staging")
  if TEMPORARY and stage and stage:FindFirstChild(r.name) then stage[r.name]:Destroy() end
end
-- Templates of rigs the project no longer has.
for _, child in folder:GetChildren() do
  if child:IsA("Model") and child:GetAttribute("ShurikenRig") and not KNOWN[child.Name] then child:Destroy() end
end
return HttpService:JSONEncode({ built = built, failed = failed, skipped = skippedParts })
`;
}

/**
 * Luau that stages some of a rig's parts as temporary meshes (EditableMesh → MeshPart, from their
 * mesh data) under ReplicatedStorage.ShurikenRigs._Staging.<Model>, for a preview rig built without
 * uploads (rigsBuilder(..., {temporary: true}) then assembles and removes them).
 */
export function stageMeshesLuau(model: string, meshes: Array<{ name: string; v: number[]; t: number[]; uv?: number[]; n?: number[]; surface?: string }>): string {
  const r = (x: number) => String(Math.round(x * 1000) / 1000);
  const u = (x: number) => String(Math.round(x * 100000) / 100000);
  const rows = meshes
    .map((m) => {
      const n = meshNormals(m);
      return `{name=${JSON.stringify(m.name)},v={${m.v.map(r).join(',')}},t={${m.t.join(',')}}${m.uv ? `,uv={${m.uv.map(u).join(',')}}` : ''}${n ? `,n={${n.map(r).join(',')}}` : ''}${m.surface ? `,surface=function(mp)\n${m.surface}\nend` : ''}}`;
    })
    .join(',\n');
  return `local AssetService = game:GetService("AssetService")
local ReplicatedStorage = game:GetService("ReplicatedStorage")
${NORMALS_FN}
local function folderIn(parent, name)
  local f = parent:FindFirstChild(name)
  if not f then
    f = Instance.new("Folder")
    f.Name = name
    f.Parent = parent
  end
  return f
end
local into = folderIn(folderIn(folderIn(ReplicatedStorage, "ShurikenRigs"), "_Staging"), ${JSON.stringify(model)})
local done = 0
for _, m in {
${rows}
} do
  local em = AssetService:CreateEditableMesh()
  local ids = table.create(#m.v // 3)
  for i = 1, #m.v, 3 do
    ids[(i + 2) // 3] = em:AddVertex(Vector3.new(m.v[i], m.v[i + 1], m.v[i + 2]))
  end
  local uvs = nil
  if m.uv then
    uvs = table.create(#m.uv // 2)
    for i = 1, #m.uv, 2 do
      uvs[(i + 1) // 2] = em:AddUV(Vector2.new(m.uv[i], m.uv[i + 1]))
    end
  end
  local faces = {}
  for i = 1, #m.t, 3 do
    local f = em:AddTriangle(ids[m.t[i] + 1], ids[m.t[i + 1] + 1], ids[m.t[i + 2] + 1])
    if uvs then em:SetFaceUVs(f, { uvs[m.t[i] + 1], uvs[m.t[i + 1] + 1], uvs[m.t[i + 2] + 1] }) end
    faces[#faces + 1] = f
  end
  if m.n then setNormals(em, faces, m.n, m.t) end
  local mp = AssetService:CreateMeshPartAsync(Content.fromObject(em))
  local old = into:FindFirstChild(m.name)
  if old then old:Destroy() end
  mp.Name = m.name
  mp:SetAttribute("ShurikenTemporaryMesh", true)
  if m.surface then m.surface(mp) end
  mp.Parent = into
  done += 1
end
return tostring(done)`;
}

/**
 * Rewrites world/Rigs.luau from the project's rigged models whose parts are all uploaded (a world rebuild
 * can only make permanent rigs: temporary meshes live in one Studio session). A model still waiting for an
 * upload is not in it, and its template in the place is left alone (not pruned): rig_build builds such a
 * model from what is uploaded plus temporary meshes for the rest.
 */
export function writeRigsBuilder(root: string): { file: string | null; rigs: string[]; waiting: string[] } {
  const store = new ModelStore(root);
  const rigs = store.rigs();
  const ready: Array<{ rig: RigSpec; parts: ModelMeta[]; assets: Record<string, string> }> = [];
  const waiting: string[] = [];
  for (const [name, rig] of Object.entries(rigs)) {
    const parts = store.parts(name);
    const assets = Object.fromEntries(parts.map((p) => [p.name, ModelStore.assetId(p)]).filter((x): x is [string, string] => !!x[1]));
    if (parts.length && Object.keys(assets).length === parts.length) ready.push({ rig, parts, assets });
    else waiting.push(name);
  }
  const file = join(root, RIGS_BUILDER_REL);
  if (!ready.length) {
    if (existsSync(file)) rmSync(file);
    return { file: null, rigs: [], waiting };
  }
  mkdirSync(join(root, 'world'), { recursive: true });
  writeFileSync(file, rigsBuilder(ready, { known: Object.keys(rigs) }), 'utf8');
  return { file, rigs: ready.map((r) => r.rig.model), waiting };
}
