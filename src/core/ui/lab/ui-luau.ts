import type { UiNode } from '@shared/ui-layout';

/**
 * UI Lab's builder: screens in the layout engine's node terms (a mockup version resolved for a form, or a capture)
 * built into Roblox exactly, by a fixed Luau interpreter reading the nodes as JSON. It is the inverse of the UI
 * capture (`roblox/ui-capture.ts`): what the Lab drew and audited is what the game shows, with no hand translation.
 *
 * In the game: `<shared>/ShurikenUi.luau` (the interpreter, `uiBuilderModule()`) and one data module per design
 * (`uiDataModule`); a client builds a screen with `ShurikenUi.screen(Data, "Shop", playerGui)` and wires behaviour by
 * path (`ui.by["Shop.Window.Buy"].Activated:Connect(…)`). States (hover, press, selected, disabled) play on their own;
 * `ui.setState(path, state)` sets selected/disabled. A UIScale fitted to the screen (`fit`) is refitted as it resizes.
 */

// Long-string quoting that can't be closed early by the data.
export function luauLong(s: string): string {
  let eq = '=';
  while (s.includes(`]${eq}]`)) eq += '=';
  return `[${eq}[${s}]${eq}]`;
}

/** Nodes as compact JSON (no runtime-only fields). */
export function uiDataJson(screens: UiNode[]): string {
  const strip = (n: UiNode): unknown => {
    const { loops: _loops, id: _id, ...rest } = n;
    return { ...rest, ...(n.kids ? { kids: n.kids.map(strip) } : {}) };
  };
  return JSON.stringify(screens.map(strip));
}

/** The interpreter (a ModuleScript's source). */
export function uiBuilderModule(): string {
  return BUILDER;
}

/** A data module: `return <json>` decoded once. */
export function uiDataModule(screens: UiNode[]): string {
  return `-- Generated by Shuriken's UI Lab from a design: change the design and build it again, not this file.\nreturn game:GetService("HttpService"):JSONDecode(${luauLong(uiDataJson(screens))})\n`;
}

/**
 * One chunk that builds the screens under `parentExpr` (Luau that evaluates to an Instance), returning
 * "built <n>" — for Edit-mode builds and the Studio fidelity check. Screens of the same name are replaced. `states`
 * (path → state) are shown as `ui.setState` shows them (a press, a selected tab), to photograph them.
 */
export function uiBuildChunk(screens: UiNode[], parentExpr: string, states: Record<string, string> = {}): string {
  return `local Build = (function()\n${BUILDER}\nend)()
local data = game:GetService("HttpService"):JSONDecode(${luauLong(uiDataJson(screens))})
local parent = ${parentExpr}
local states = game:GetService("HttpService"):JSONDecode(${luauLong(JSON.stringify(states))})
local n = 0
for _, s in data do
  local old = parent:FindFirstChild(s.name)
  if old then old:Destroy() end
  local ui = Build.screen(data, s.name, parent)
  for path, state in states do ui.setState(path, state) end
  n += 1
end
return "built " .. n`;
}

const BUILDER = `--!nocheck
-- ShurikenUi: builds ScreenGuis from UI Lab data (generated by Shuriken; don't edit).
local TweenService = game:GetService("TweenService")
local GuiService = game:GetService("GuiService")

local B = {}

local function c3(t) return Color3.fromRGB(t[1], t[2], t[3]) end
local function udim(t) return UDim.new(t[1], t[2]) end
local function udim2(t) return UDim2.new(t[1], t[2], t[3], t[4]) end
local function enum(e, name, fallback)
  local ok, v = pcall(function() return e[name] end)
  if ok and v then return v end
  return fallback
end

local function colorSeq(keys)
  local ks = {}
  for _, k in keys do table.insert(ks, ColorSequenceKeypoint.new(k[1], Color3.fromRGB(k[2], k[3], k[4]))) end
  return ColorSequence.new(ks)
end
local function numberSeq(keys)
  local ks = {}
  for _, k in keys do table.insert(ks, NumberSequenceKeypoint.new(k[1], k[2])) end
  return NumberSequence.new(ks)
end

local function gradient(g, parent)
  local m = Instance.new("UIGradient")
  m.Rotation = g.rot or 0
  if g.colors and #g.colors > 0 then m.Color = colorSeq(g.colors) end
  if g.transp and #g.transp > 0 then m.Transparency = numberSeq(g.transp) end
  if g.offset then m.Offset = Vector2.new(g.offset[1], g.offset[2]) end
  -- The enum is Enum.GradientType (measured: Enum.UIGradientType doesn't exist).
  if g.type and g.type ~= "Linear" then pcall(function() m.Type = Enum.GradientType[g.type] end) end
  m.Parent = parent
  return m
end

-- A Roblox font from what a node carries: an Enum.Font name (mockups) or a FontFace family (captures).
local function fontFace(name, bold, italic, weight)
  name = name or "BuilderSans"
  local ff
  local e = enum(Enum.Font, name, nil)
  if e then
    ff = Font.fromEnum(e)
  else
    ff = Font.new("rbxasset://fonts/families/" .. name .. ".json")
  end
  local w = ff.Weight
  if weight then
    for _, item in Enum.FontWeight:GetEnumItems() do
      if item.Value == weight then w = item end
    end
  elseif bold and w.Value < 600 then
    w = Enum.FontWeight.Bold
  end
  return Font.new(ff.Family, w, if italic then Enum.FontStyle.Italic else ff.Style)
end

local function stroke(s, parent)
  local m = Instance.new("UIStroke")
  m.Color = c3(s.color)
  m.Transparency = s.t or 0
  m.Thickness = s.px or 1
  m.ApplyStrokeMode = if s.text then Enum.ApplyStrokeMode.Contextual else Enum.ApplyStrokeMode.Border
  if s.pos then pcall(function() m.BorderStrokePosition = Enum.BorderStrokePosition[s.pos] end) end
  if s.z then pcall(function() m.ZIndex = s.z end) end
  if s.gradient then gradient(s.gradient, m) end
  m.Parent = parent
  return m
end

local function shadow(s, parent)
  local ok, m = pcall(Instance.new, "UIShadow")
  if not ok then return nil end
  pcall(function()
    m.Color = c3(s.color)
    m.Transparency = s.t or 0
    m.BlurRadius = UDim.new(0, s.blur or 0)
    if s.spread then m.Spread = UDim2.fromOffset(s.spread, s.spread) end
    if s.offset then m.Offset = UDim2.fromOffset(s.offset[1], s.offset[2]) end
  end)
  m.Parent = parent
  return m
end

-- An element's UIStrokes set to a list (a state's ring or glow replaces its outlines; the normal look puts them back):
-- the first ones are reused, more are made, the rest switched off.
local function strokeList(p)
  if p.strokes then return p.strokes end
  if p.stroke then return if p.stroke[1] then p.stroke else { p.stroke } end
  return {}
end
local function applyStrokes(o, mods, list)
  mods.strokes = mods.strokes or {}
  for i, s in list do
    local m = mods.strokes[i]
    if m then
      m.Color = c3(s.color)
      m.Transparency = s.t or 0
      m.Thickness = s.px or 1
      if s.z then pcall(function() m.ZIndex = s.z end) end
      if s.pos then pcall(function() m.BorderStrokePosition = Enum.BorderStrokePosition[s.pos] end) end
    else
      m = stroke(s, o)
      mods.strokes[i] = m
    end
    m.Enabled = true
  end
  for i = #list + 1, #mods.strokes do mods.strokes[i].Enabled = false end
end

-- A state's gradient or shadow replaces the element's (none: switched off), the normal look puts its own back.
local function applyGradient(o, mods, g)
  if not g then
    if mods.gradient then mods.gradient.Enabled = false end
    return
  end
  if not mods.gradient then mods.gradient = gradient(g, o) return end
  local m = mods.gradient
  m.Rotation = g.rot or 0
  m.Color = if g.colors and #g.colors > 0 then colorSeq(g.colors) else ColorSequence.new(Color3.new(1, 1, 1))
  m.Transparency = if g.transp and #g.transp > 0 then numberSeq(g.transp) else NumberSequence.new(0)
  m.Offset = if g.offset then Vector2.new(g.offset[1], g.offset[2]) else Vector2.zero
  m.Enabled = true
end
local function applyShadow(o, mods, sh)
  if not sh then
    if mods.shadow then pcall(function() mods.shadow.Enabled = false end) end
    return
  end
  if not mods.shadow then mods.shadow = shadow(sh, o) return end
  pcall(function()
    local m = mods.shadow
    m.Color = c3(sh.color)
    m.Transparency = sh.t or 0
    m.BlurRadius = UDim.new(0, sh.blur or 0)
    m.Spread = UDim2.fromOffset(sh.spread or 0, sh.spread or 0)
    m.Offset = UDim2.fromOffset(sh.offset and sh.offset[1] or 0, sh.offset and sh.offset[2] or 0)
    m.Enabled = true
  end)
end

-- The look a state changes (its patch), applied to an element and its modifiers.
local function applyLook(o, mods, p)
  if p.bg then o.BackgroundColor3 = c3(p.bg) end
  if p.bgT then o.BackgroundTransparency = p.bgT end
  if p.textColor and o:IsA("GuiObject") and (o:IsA("TextLabel") or o:IsA("TextButton") or o:IsA("TextBox")) then o.TextColor3 = c3(p.textColor) end
  if p.textT and (o:IsA("TextLabel") or o:IsA("TextButton") or o:IsA("TextBox")) then o.TextTransparency = p.textT end
  if p.imageColor and (o:IsA("ImageLabel") or o:IsA("ImageButton")) then o.ImageColor3 = c3(p.imageColor) end
  if p.imageT and (o:IsA("ImageLabel") or o:IsA("ImageButton")) then o.ImageTransparency = p.imageT end
  if p.rot then o.Rotation = p.rot end
end

local function build(n, parent, path, out)
  local o = Instance.new(n.cls)
  o.Name = n.name
  out.by[path] = o
  local mods = {}
  if o:IsA("ScreenGui") then
    o.ResetOnSpawn = false
    if n.enabled ~= nil then o.Enabled = n.enabled end
    o.IgnoreGuiInset = n.ignoreInset == true
    if n.insets then pcall(function() o.ScreenInsets = Enum.ScreenInsets[n.insets] end) end
    o.DisplayOrder = n.displayOrder or 0
    o.ZIndexBehavior = if n.global then Enum.ZIndexBehavior.Global else Enum.ZIndexBehavior.Sibling
  elseif o:IsA("GuiObject") then
    if n.visible ~= nil then o.Visible = n.visible end
    if n.pos then o.Position = udim2(n.pos) end
    if n.size then o.Size = udim2(n.size) end
    if n.anchor then o.AnchorPoint = Vector2.new(n.anchor[1], n.anchor[2]) end
    if n.rot then o.Rotation = n.rot end
    if n.z then o.ZIndex = n.z end
    if n.order then o.LayoutOrder = n.order end
    o.BackgroundColor3 = if n.bg then c3(n.bg) else Color3.new(1, 1, 1)
    o.BackgroundTransparency = if n.bgT ~= nil then n.bgT else (if n.bg then 0 else 1)
    o.BorderSizePixel = n.border or 0
    if n.borderColor then o.BorderColor3 = c3(n.borderColor) end
    if n.clips then o.ClipsDescendants = true end
    if n.auto then o.AutomaticSize = enum(Enum.AutomaticSize, n.auto, Enum.AutomaticSize.None) end
    if o:IsA("TextLabel") or o:IsA("TextButton") or o:IsA("TextBox") then
      o.FontFace = fontFace(n.font, n.bold, n.italic, n.weight)
      o.Text = n.text or ""
      if o:IsA("TextBox") then o.ClearTextOnFocus = false end
      o.TextColor3 = if n.textColor then c3(n.textColor) else Color3.new(0, 0, 0)
      o.TextTransparency = n.textT or 0
      o.TextSize = n.textSize or 14
      -- TextWrapped first: setting it false after TextScaled turns TextScaled off (measured in Studio).
      o.TextWrapped = n.wrapped == true
      o.TextScaled = n.scaled == true
      o.TextXAlignment = enum(Enum.TextXAlignment, n.xAlign or "Center", Enum.TextXAlignment.Center)
      o.TextYAlignment = enum(Enum.TextYAlignment, n.yAlign or "Center", Enum.TextYAlignment.Center)
      o.TextStrokeTransparency = if n.strokeT ~= nil then n.strokeT else 1
      if n.strokeColor then o.TextStrokeColor3 = c3(n.strokeColor) end
      o.RichText = n.rich == true
      if n.truncate then o.TextTruncate = Enum.TextTruncate.AtEnd end
      if n.lineHeight then o.LineHeight = n.lineHeight end
    end
    if o:IsA("ImageLabel") or o:IsA("ImageButton") then
      if n.image and string.find(n.image, "^rbxasset") then o.Image = n.image end
      if n.imageColor then o.ImageColor3 = c3(n.imageColor) end
      o.ImageTransparency = n.imageT or 0
      if n.scaleType then o.ScaleType = enum(Enum.ScaleType, n.scaleType, Enum.ScaleType.Stretch) end
      if n.slice then o.SliceCenter = Rect.new(n.slice[1], n.slice[2], n.slice[3], n.slice[4]) end
      if n.sliceScale then o.SliceScale = n.sliceScale end
      if n.resample then pcall(function() o.ResampleMode = Enum.ResamplerMode[n.resample] end) end
      if n.rect then
        o.ImageRectOffset = Vector2.new(n.rect[1], n.rect[2])
        o.ImageRectSize = Vector2.new(n.rect[3], n.rect[4])
      end
    end
    if o:IsA("TextButton") or o:IsA("ImageButton") then o.AutoButtonColor = false end
    if o:IsA("ScrollingFrame") and n.canvas then o.CanvasSize = udim2(n.canvas) end
  end
  -- Modifiers, as the capture folds them.
  if n.corner or n.corners then
    local m = Instance.new("UICorner")
    m.CornerRadius = udim(n.corner or n.corners[1])
    if n.corners then
      pcall(function()
        m.TopLeftRadius = udim(n.corners[1]); m.TopRightRadius = udim(n.corners[2])
        m.BottomRightRadius = udim(n.corners[3]); m.BottomLeftRadius = udim(n.corners[4])
      end)
    end
    m.Parent = o
  end
  mods.strokes = {}
  for _, s in (n.strokes or (if n.stroke then { n.stroke } else {})) do table.insert(mods.strokes, stroke(s, o)) end
  if n.gradient then mods.gradient = gradient(n.gradient, o) end
  if n.shadow then mods.shadow = shadow(n.shadow, o) end
  if n.padding then
    local m = Instance.new("UIPadding")
    m.PaddingTop = udim(n.padding[1]); m.PaddingRight = udim(n.padding[2])
    m.PaddingBottom = udim(n.padding[3]); m.PaddingLeft = udim(n.padding[4])
    m.Parent = o
  end
  if n.list then
    local l = n.list
    local m = Instance.new("UIListLayout")
    m.FillDirection = enum(Enum.FillDirection, l.dir or "Vertical", Enum.FillDirection.Vertical)
    m.HorizontalAlignment = enum(Enum.HorizontalAlignment, l.h or "Left", Enum.HorizontalAlignment.Left)
    m.VerticalAlignment = enum(Enum.VerticalAlignment, l.v or "Top", Enum.VerticalAlignment.Top)
    if l.pad then m.Padding = udim(l.pad) end
    m.SortOrder = if l.byName then Enum.SortOrder.Name else Enum.SortOrder.LayoutOrder
    pcall(function()
      if l.hFlex then m.HorizontalFlex = Enum.UIFlexAlignment[l.hFlex] end
      if l.vFlex then m.VerticalFlex = Enum.UIFlexAlignment[l.vFlex] end
      if l.wraps then m.Wraps = true end
      if l.itemAlign then m.ItemLineAlignment = Enum.ItemLineAlignment[l.itemAlign] end
    end)
    m.Parent = o
  end
  if n.grid then
    local g = n.grid
    local m = Instance.new("UIGridLayout")
    if g.cell then m.CellSize = udim2(g.cell) end
    if g.pad then m.CellPadding = udim2(g.pad) end
    m.FillDirection = enum(Enum.FillDirection, g.dir or "Horizontal", Enum.FillDirection.Horizontal)
    m.HorizontalAlignment = enum(Enum.HorizontalAlignment, g.h or "Left", Enum.HorizontalAlignment.Left)
    m.VerticalAlignment = enum(Enum.VerticalAlignment, g.v or "Top", Enum.VerticalAlignment.Top)
    m.SortOrder = if g.byName then Enum.SortOrder.Name else Enum.SortOrder.LayoutOrder
    if g.max then m.FillDirectionMaxCells = g.max end
    m.Parent = o
  end
  if n.pages then
    local m = Instance.new("UIPageLayout")
    m.SortOrder = if n.pages.byName then Enum.SortOrder.Name else Enum.SortOrder.LayoutOrder
    m.Parent = o
    mods.pages = { layout = m, current = n.pages.current }
  end
  if n.flex then
    local m = Instance.new("UIFlexItem")
    m.FlexMode = enum(Enum.UIFlexMode, n.flex.mode or "None", Enum.UIFlexMode.None)
    if n.flex.grow then m.GrowRatio = n.flex.grow end
    if n.flex.shrink then m.ShrinkRatio = n.flex.shrink end
    if n.flex.align then m.ItemLineAlignment = enum(Enum.ItemLineAlignment, n.flex.align, Enum.ItemLineAlignment.Automatic) end
    m.Parent = o
  end
  if n.aspect then
    local m = Instance.new("UIAspectRatioConstraint")
    m.AspectRatio = n.aspect.ratio
    if n.aspect.scaleWithParent then m.AspectType = Enum.AspectType.ScaleWithParentSize end
    if n.aspect.heightDominant then m.DominantAxis = Enum.DominantAxis.Height end
    m.Parent = o
  end
  if n.sizeMin or n.sizeMax then
    local m = Instance.new("UISizeConstraint")
    if n.sizeMin then m.MinSize = Vector2.new(n.sizeMin[1], n.sizeMin[2]) end
    if n.sizeMax then m.MaxSize = Vector2.new(if n.sizeMax[1] >= 1e9 then math.huge else n.sizeMax[1], if n.sizeMax[2] >= 1e9 then math.huge else n.sizeMax[2]) end
    m.Parent = o
  end
  if n.textMin or n.textMax then
    local m = Instance.new("UITextSizeConstraint")
    if n.textMin then m.MinTextSize = n.textMin end
    if n.textMax then m.MaxTextSize = n.textMax end
    m.Parent = o
  end
  local needsScale = n.scale ~= nil or n.fit ~= nil or (n.states and (function()
    for _, p in n.states do if p.scale then return true end end
    return false
  end)())
  if needsScale then
    local m = Instance.new("UIScale")
    m.Scale = n.scale or 1
    if n.fit then
      m:SetAttribute("FitReference", Vector2.new(n.fit.ref[1], n.fit.ref[2]))
      m:SetAttribute("FitRange", NumberRange.new(n.fit.min, math.max(n.fit.min, n.fit.max)))
      if n.fit.tenFoot then m:SetAttribute("FitTenFoot", n.fit.tenFoot) end
      table.insert(out.fits, { scale = m, fit = n.fit })
    end
    m.Parent = o
    mods.scale = m
  end
  -- A folder's children keep their parent's path (a skin's art and text live in one).
  for _, k in (n.kids or {}) do build(k, o, if n.cls == "Folder" then string.match(path, "^(.*)%.[^%.]+$") .. "." .. k.name else path .. "." .. k.name, out) end
  if mods.pages and mods.pages.current then
    local page = o:FindFirstChild(mods.pages.current)
    if page then pcall(function() mods.pages.layout:JumpTo(page) end) end
  end
  if n.states then out.stated[path] = { o = o, mods = mods, node = n, base = n.scale or 1 } end
  o.Parent = parent
  return o
end

-- A state's forged art on its "Skin" child (a pressed button, an active tab), or the element's own art back.
local function showArt(s, a)
  local holder = s.o:FindFirstChild("Art") or s.o
  local art = holder:FindFirstChild("Skin")
  if not art or not art:IsA("ImageLabel") then return end
  if not s.artBase then
    s.artBase = { image = art.Image, scaleType = art.ScaleType, slice = art.SliceCenter, sliceScale = art.SliceScale, pos = art.Position, size = art.Size, rectOffset = art.ImageRectOffset, rectSize = art.ImageRectSize }
  end
  if a then
    if string.find(a.image, "^rbxasset") then art.Image = a.image end
    art.ScaleType = enum(Enum.ScaleType, a.scaleType, Enum.ScaleType.Stretch)
    if a.slice then art.SliceCenter = Rect.new(a.slice[1], a.slice[2], a.slice[3], a.slice[4]) end
    if a.sliceScale then art.SliceScale = a.sliceScale end
    art.Position = udim2(a.pos)
    art.Size = udim2(a.size)
    if a.rect then
      art.ImageRectOffset = Vector2.new(a.rect[1], a.rect[2])
      art.ImageRectSize = Vector2.new(a.rect[3], a.rect[4])
    end
  else
    local b = s.artBase
    art.Image, art.ScaleType, art.SliceCenter, art.SliceScale, art.Position, art.Size = b.image, b.scaleType, b.slice, b.sliceScale, b.pos, b.size
    art.ImageRectOffset, art.ImageRectSize = b.rectOffset, b.rectSize
  end
end

-- A state's changes to a skinned element's text (its "Label" child): a pressed face moves it, colours change.
local function showLabel(s, l)
  local label = (s.o:FindFirstChild("Art") or s.o):FindFirstChild("Label")
  if not label or not label:IsA("TextLabel") then return end
  local function letters()
    for _, c in label:GetChildren() do
      if c:IsA("UIStroke") and c.ApplyStrokeMode == Enum.ApplyStrokeMode.Contextual then return c end
    end
    return nil
  end
  if not s.labelBase then
    local st = letters()
    s.labelBase = { pos = label.Position, size = label.Size, color = label.TextColor3, t = label.TextTransparency, stroke = if st then { color = st.Color, px = st.Thickness, t = st.Transparency } else false }
  end
  local b = s.labelBase
  label.Position = if l and l.pos then udim2(l.pos) else b.pos
  label.Size = if l and l.size then udim2(l.size) else b.size
  label.TextColor3 = if l and l.textColor then c3(l.textColor) else b.color
  label.TextTransparency = if l and l.textT then l.textT else b.t
  -- The letters' outline in the state (created when the normal look has none).
  local st = letters()
  if l and l.stroke then
    if not st then
      st = Instance.new("UIStroke")
      st.ApplyStrokeMode = Enum.ApplyStrokeMode.Contextual
      st.Parent = label
    end
    st.Color = c3(l.stroke.color)
    st.Thickness = l.stroke.px or 1
    st.Transparency = l.stroke.t or 0
  elseif st then
    if b.stroke then
      st.Color, st.Thickness, st.Transparency = b.stroke.color, b.stroke.px, b.stroke.t
    else
      st.Transparency = 1
    end
  end
end

-- A state's look on (or back to normal): colours and transparencies at once, the scale with a short tween.
local function showState(s, state)
  local n = s.node
  local p = if state then n.states[state] else nil
  applyLook(s.o, s.mods, n)
  if s.hasArt == nil then
    s.hasArt, s.hasLabel, s.hasStroke, s.hasGradient, s.hasShadow = false, false, false, false, false
    for _, q in n.states do
      if q.skinArt then s.hasArt = true end
      if q.label then s.hasLabel = true end
      if q.stroke or q.strokes then s.hasStroke = true end
      if q.gradient then s.hasGradient = true end
      if q.shadow then s.hasShadow = true end
    end
  end
  if s.hasArt then showArt(s, p and p.skinArt) end
  if s.hasLabel then showLabel(s, p and p.label) end
  if s.hasStroke then applyStrokes(s.o, s.mods, if p and (p.stroke or p.strokes) then strokeList(p) else strokeList(n)) end
  if s.hasGradient then applyGradient(s.o, s.mods, if p and p.gradient then p.gradient else n.gradient) end
  if s.hasShadow then applyShadow(s.o, s.mods, if p and p.shadow then p.shadow else n.shadow) end
  local k = s.base
  if p then
    applyLook(s.o, s.mods, p)
    if p.scale then k = s.base * p.scale end
  end
  if s.mods.scale then
    TweenService:Create(s.mods.scale, TweenInfo.new(if state == "press" then 0.08 else 0.14, Enum.EasingStyle.Quad, Enum.EasingDirection.Out), { Scale = k }):Play()
  end
end

local function wire(s)
  local o = s.o
  local hovered, pressed = false, false
  local function now()
    if s.forced then return showState(s, s.forced) end
    if pressed and s.node.states.press then return showState(s, "press") end
    if hovered and s.node.states.hover then return showState(s, "hover") end
    showState(s, nil)
  end
  s.refresh = now
  if o:IsA("GuiButton") then
    o.MouseEnter:Connect(function() hovered = true; now() end)
    o.MouseLeave:Connect(function() hovered = false; pressed = false; now() end)
    o.MouseButton1Down:Connect(function() pressed = true; now() end)
    o.MouseButton1Up:Connect(function() pressed = false; now() end)
  end
end

local function fitScale(gui, f)
  local size = gui.AbsoluteSize
  if size.X <= 0 or size.Y <= 0 then return end
  local k = math.clamp(math.min(size.X / f.fit.ref[1], size.Y / f.fit.ref[2]), f.fit.min, math.max(f.fit.min, f.fit.max))
  if f.fit.tenFoot and GuiService:IsTenFootInterface() then k *= f.fit.tenFoot end
  f.scale.Scale = k
end

--- Builds the screen named \`name\` from \`data\` (an array of screen nodes) under \`parent\`.
--- Returns { gui, by = {[path] = Instance}, setState(path, state?) }.
function B.screen(data, name, parent)
  local node
  for _, s in data do if s.name == name then node = s end end
  assert(node, "ShurikenUi: no screen named " .. tostring(name))
  local out = { by = {}, stated = {}, fits = {} }
  local gui = build(node, nil, node.name, out)
  for _, s in out.stated do
    wire(s)
    -- The state it starts in (the open tab, a button not usable yet).
    if s.node.state then
      s.forced = s.node.state
      s.refresh()
    end
  end
  if #out.fits > 0 then
    local function refit() for _, f in out.fits do fitScale(gui, f) end end
    gui:GetPropertyChangedSignal("AbsoluteSize"):Connect(refit)
    task.defer(refit)
  end
  -- Roblox's own UI the screen hides while it is open (restored when it closes).
  if node.hides then
    local StarterGui = game:GetService("StarterGui")
    local types = { chat = Enum.CoreGuiType.Chat, playerList = Enum.CoreGuiType.PlayerList, backpack = Enum.CoreGuiType.Backpack }
    local function hide(on)
      for w in string.gmatch(node.hides, "[%a]+") do
        if w == "touch" then
          pcall(function() GuiService.TouchControlsEnabled = not on end)
        elseif types[w] then
          pcall(function() StarterGui:SetCoreGuiEnabled(types[w], not on) end)
        end
      end
    end
    gui:GetPropertyChangedSignal("Enabled"):Connect(function() hide(gui.Enabled) end)
    if node.enabled ~= false then task.defer(hide, true) end
  end
  gui.Parent = parent
  local api = { gui = gui, by = out.by }
  function api.setState(path, state)
    local s = out.stated[path]
    if not s then return end
    s.forced = state
    s.refresh()
  end
  return api
end

return B`;
