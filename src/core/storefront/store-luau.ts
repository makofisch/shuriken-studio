import type { StoreItem } from './storefront';

/** Raised when the runtime below changes: a game's module older than this is written again. */
export const STORE_RUNTIME_VERSION = 1;

const str = (s: string) => JSON.stringify(s);

/**
 * The game's ShurikenStore module (generated into its shared code, synced like any script): what the game sells,
 * with each item's Roblox id (0 until it is pushed), and the one place that answers Roblox's purchase callbacks.
 * Game passes are checked on join and on purchase and kept as a player attribute (ShurikenPass_<Key>) the client can
 * read; developer products go through ProcessReceipt, each purchase granted once (the ledger: the player's saved
 * profile, given with Store.useLedger). In Studio an item that isn't on Roblox yet is bought as a test purchase,
 * granted the same way, so the whole flow is built and tested before anything is pushed.
 */
export function storeModule(items: StoreItem[]): string {
  const rows = items.map((i) => `\t[${str(i.key)}] = { key = ${str(i.key)}, kind = ${str(i.kind)}, id = ${i.roblox?.id ?? 0}, price = ${Math.round(i.price)}, name = ${str(i.name)} } :: Item,`);
  return `--!strict
-- ShurikenStore v${STORE_RUNTIME_VERSION} (generated by Shuriken Studio from .shuriken/storefront/catalog.json). Do not edit:
-- change the store on the Storefront page or with store_catalog.
--
-- What the game sells. Require it from a server script when the server starts (it answers Roblox's purchase
-- callbacks; nothing else may set MarketplaceService.ProcessReceipt) and from the client to show and offer items.
--   Store.items.<Key>                  {key, kind "pass"|"product", id, price, name}; id 0 until pushed to Roblox
--   Store.owns(player, key)            a pass: whether the player owns it (server or client; on the client, nil = you)
--   Store.onPass(key, fn)              server: fn(player) when a player has the pass, on join and on purchase
--   Store.onProduct(key, fn)           server: fn(player, receipt) -> true once granted; each purchase is granted once
--   Store.useLedger(has, add)          server: has(player, purchaseId) / add(player, purchaseId) in the saved profile;
--                                      add returns false when it couldn't save (Roblox asks again later)
--   Store.prompt(key) / prompt(player, key)   offers the item (on the client, to the local player)
--   Store.otherReceipts(fn)            server: a game that sold products before keeps its own: fn(receipt) answers
--                                      the receipts of products that aren't in this store
--   Store.changed:Connect(fn)          fn(player, key) when a player gets a pass (client and server)
-- In Studio, an item that isn't on Roblox yet is bought as a test purchase and granted the same way.
local MarketplaceService = game:GetService("MarketplaceService")
local Players = game:GetService("Players")
local ReplicatedStorage = game:GetService("ReplicatedStorage")
local RunService = game:GetService("RunService")

export type Item = { key: string, kind: string, id: number, price: number, name: string }

local Store = {}

Store.items = {
${rows.join('\n')}
} :: { [string]: Item }

local IS_SERVER = RunService:IsServer()
local IS_STUDIO = RunService:IsStudio()
local TEST_REMOTE = "ShurikenStoreTest"

local changedEvent = Instance.new("BindableEvent")
Store.changed = changedEvent.Event

-- Passes and products are looked up apart: their ids are not from one series.
local passById: { [number]: Item } = {}
local productById: { [number]: Item } = {}
for _, item in Store.items do
	if item.id ~= 0 then
		if item.kind == "pass" then
			passById[item.id] = item
		else
			productById[item.id] = item
		end
	end
end

local function attr(key: string): string
	return "ShurikenPass_" .. key
end

function Store.owns(player: Player?, key: string): boolean
	local p = player or (if IS_SERVER then nil else Players.LocalPlayer)
	if not p then
		return false
	end
	return p:GetAttribute(attr(key)) == true
end

local passHandlers: { [string]: { (Player) -> () } } = {}
local productHandlers: { [string]: (Player, { [string]: any }) -> boolean } = {}
local granted: { [string]: boolean } = {}
local ledgerHas = function(_player: Player, purchaseId: string): boolean
	return granted[purchaseId] == true
end
local ledgerAdd = function(_player: Player, purchaseId: string): boolean?
	granted[purchaseId] = true
	return true
end

function Store.useLedger(has: (Player, string) -> boolean, add: (Player, string) -> boolean?)
	ledgerHas = has
	ledgerAdd = add
end

local otherReceipts: ((receipt: { [string]: any }) -> Enum.ProductPurchaseDecision)? = nil

function Store.otherReceipts(fn: (receipt: { [string]: any }) -> Enum.ProductPurchaseDecision)
	otherReceipts = fn
end

local function grantPass(player: Player, item: Item)
	if player:GetAttribute(attr(item.key)) == true then
		return
	end
	player:SetAttribute(attr(item.key), true)
	local list = passHandlers[item.key]
	if list then
		for _, fn in list do
			task.spawn(fn, player)
		end
	end
	changedEvent:Fire(player, item.key)
end

function Store.onPass(key: string, fn: (Player) -> ())
	assert(IS_SERVER, "Store.onPass runs on the server")
	local item = Store.items[key]
	assert(item and item.kind == "pass", "ShurikenStore: no pass " .. key)
	local list = passHandlers[key] or {}
	table.insert(list, fn)
	passHandlers[key] = list
	for _, p in Players:GetPlayers() do
		if Store.owns(p, key) then
			task.spawn(fn, p)
		end
	end
end

function Store.onProduct(key: string, fn: (Player, { [string]: any }) -> boolean)
	assert(IS_SERVER, "Store.onProduct runs on the server")
	local item = Store.items[key]
	assert(item and item.kind == "product", "ShurikenStore: no product " .. key)
	productHandlers[key] = fn
end

local function grantProduct(player: Player, item: Item, receipt: { [string]: any }): boolean
	local fn = productHandlers[item.key]
	if not fn then
		warn("ShurikenStore: nothing grants " .. item.key .. " (Store.onProduct)")
		return false
	end
	local ok, result = pcall(fn, player, receipt)
	if not ok then
		warn("ShurikenStore: granting " .. item.key .. " failed: " .. tostring(result))
		return false
	end
	return result == true
end

local tests = 0
local function testPurchase(player: Player, item: Item)
	if item.kind == "pass" then
		grantPass(player, item)
		return
	end
	tests += 1
	local purchaseId = "studio-test-" .. tests
	local receipt = { PlayerId = player.UserId, ProductId = 0, PurchaseId = purchaseId, CurrencySpent = item.price, PlaceIdWherePurchased = game.PlaceId }
	if grantProduct(player, item, receipt) then
		ledgerAdd(player, purchaseId)
	end
end

if IS_SERVER then
	local function checkPasses(player: Player)
		for _, item in Store.items do
			if item.kind == "pass" and item.id ~= 0 then
				local ok, has = pcall(function()
					return MarketplaceService:UserOwnsGamePassAsync(player.UserId, item.id)
				end)
				if ok and has then
					grantPass(player, item)
				end
			end
		end
	end
	Players.PlayerAdded:Connect(checkPasses)
	for _, p in Players:GetPlayers() do
		task.spawn(checkPasses, p)
	end
	MarketplaceService.PromptGamePassPurchaseFinished:Connect(function(player: Player, passId: number, purchased: boolean)
		local item = passById[passId]
		if purchased and item then
			grantPass(player, item)
		end
	end)
	MarketplaceService.ProcessReceipt = function(receipt)
		local item = productById[receipt.ProductId]
		if not item then
			-- A product this store doesn't sell: the game's own handler, if it gave one.
			local other = otherReceipts
			if other then
				return other(receipt :: any)
			end
			return Enum.ProductPurchaseDecision.NotProcessedYet
		end
		local player = Players:GetPlayerByUserId(receipt.PlayerId)
		if not player then
			return Enum.ProductPurchaseDecision.NotProcessedYet
		end
		local purchaseId = tostring(receipt.PurchaseId)
		if ledgerHas(player, purchaseId) then
			return Enum.ProductPurchaseDecision.PurchaseGranted
		end
		if not grantProduct(player, item, receipt :: any) then
			return Enum.ProductPurchaseDecision.NotProcessedYet
		end
		-- Granted only once it is saved: a failed save is asked again (has() then finds it and the grant isn't repeated).
		if ledgerAdd(player, purchaseId) == false then
			return Enum.ProductPurchaseDecision.NotProcessedYet
		end
		return Enum.ProductPurchaseDecision.PurchaseGranted
	end
	-- Test purchases only in a playtest: a remote made in Edit would be saved with the place and answered by nobody.
	if IS_STUDIO and RunService:IsRunning() then
		local remote = ReplicatedStorage:FindFirstChild(TEST_REMOTE) :: RemoteEvent?
		if not remote then
			local made = Instance.new("RemoteEvent")
			made.Name = TEST_REMOTE
			made.Parent = ReplicatedStorage
			remote = made
		end
		local testRemote = remote :: RemoteEvent
		testRemote.OnServerEvent:Connect(function(player: Player, key: unknown)
			local item = if typeof(key) == "string" then Store.items[key] else nil
			if item and item.id == 0 then
				testPurchase(player, item)
			end
		end)
	end
else
	-- The client hears of passes the server grants (the attribute replicates).
	local me = Players.LocalPlayer
	if me then
		me.AttributeChanged:Connect(function(name: string)
			local key = string.match(name, "^ShurikenPass_(.+)$")
			if key and me:GetAttribute(name) == true then
				changedEvent:Fire(me, key)
			end
		end)
	end
end

function Store.prompt(a: Player | string, b: string?)
	local player: Player? = nil
	local key: string
	if typeof(a) == "Instance" then
		player = a :: Player
		key = b or ""
	else
		player = if IS_SERVER then nil else Players.LocalPlayer
		key = a :: string
	end
	local item = Store.items[key]
	if not item or not player then
		warn("ShurikenStore: can't offer " .. tostring(key))
		return
	end
	if item.id == 0 then
		if not IS_STUDIO then
			warn("ShurikenStore: " .. key .. " isn't on Roblox yet: push it from Shuriken's Storefront")
		elseif IS_SERVER then
			testPurchase(player, item)
		else
			local remote = ReplicatedStorage:WaitForChild(TEST_REMOTE, 5) :: RemoteEvent?
			if remote then
				remote:FireServer(key)
			end
		end
		return
	end
	if item.kind == "pass" then
		MarketplaceService:PromptGamePassPurchase(player, item.id)
	else
		MarketplaceService:PromptProductPurchase(player, item.id)
	end
end

return Store
`;
}
