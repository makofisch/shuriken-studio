const num = (v: number) => String(Math.round(v * 1000) / 1000);
const str = (s: string) => JSON.stringify(s);
const list = (v: number[]) => `{${v.map(num).join(',')}}`;
const strs = (v: string[]) => `{${v.map(str).join(',')}}`;
/** A Luau long string that can't be closed early by its content. */
function longString(s: string): string {
  let eq = '==';
  while (s.includes(`]${eq}]`)) eq += '=';
  return `[${eq}[${s}]${eq}]`;
}

/** Keypoints a NumberSequence/ColorSequence accepts: ascending, starting at 0 and ending at 1, at most 20. */
function normKeys<T>(keys: Array<[number, T]>): Array<[number, T]> {
  const sorted = [...keys].sort((a, b) => a[0] - b[0]).slice(0, 20);
  if (!sorted.length) return sorted;
  if (sorted[0]![0] > 0) sorted.unshift([0, sorted[0]![1]]);
  if (sorted[sorted.length - 1]![0] < 1) sorted.push([1, sorted[sorted.length - 1]![1]]);
  const out: Array<[number, T]> = [];
  for (const [t, v] of sorted.slice(0, 20)) {
    const prev = out[out.length - 1];
    const time = Math.min(1, Math.max(0, t));
    out.push([prev && time <= prev[0] ? Math.min(1, prev[0] + 1e-3) : time, v]);
  }
  out[0]![0] = 0;
  out[out.length - 1]![0] = 1;
  return out;
}
const numKeys = (k: Array<[number, number]>) => `{${normKeys(k).map(([t, v]) => `{${num(t)},${num(v)}}`).join(',')}}`;
const colKeys = (k: Array<[number, string]>) => `{${normKeys(k).map(([t, c]) => `{${num(t)},${str(c)}}`).join(',')}}`;

type Resolve = (texture: string | undefined) => string | undefined;

function emitterTable(m: CompiledEmitter, tex: Resolve): string {
  const f: string[] = [
    `name=${str(m.name)}`,
    `texture=${str(tex(m.texture) ?? m.texture)}`,
    `color=${colKeys(m.color)}`,
    `size=${numKeys(m.size)}`,
    `transparency=${numKeys(m.transparency)}`,
    `lifetime=${list(m.lifetime)}`,
    `speed=${list(m.speed)}`,
  ];
  if (m.spread) f.push(`spread=${list(m.spread)}`);
  if (m.rate !== undefined) f.push(`rate=${num(m.rate)}`);
  if (m.emit !== undefined) f.push(`emit=${num(m.emit)}`);
  if (m.delay) f.push(`delay=${num(m.delay)}`);
  if (m.for) f.push(`emitFor=${num(m.for)}`);
  if (m.drag !== undefined) f.push(`drag=${num(m.drag)}`);
  if (m.acceleration) f.push(`acceleration=${list(m.acceleration)}`);
  if (m.lightEmission !== undefined) f.push(`lightEmission=${num(m.lightEmission)}`);
  if (m.lightInfluence !== undefined) f.push(`lightInfluence=${num(m.lightInfluence)}`);
  if (m.brightness !== undefined) f.push(`brightness=${num(m.brightness)}`);
  if (m.rotation) f.push(`rotation=${list(m.rotation)}`);
  if (m.rotSpeed) f.push(`rotSpeed=${list(m.rotSpeed)}`);
  if (m.orientation) f.push(`orientation=${str(m.orientation)}`);
  if (m.squash) f.push(`squash=${numKeys(m.squash)}`);
  if (m.zOffset !== undefined) f.push(`zOffset=${num(m.zOffset)}`);
  if (m.lockedToPart) f.push('lockedToPart=true');
  if (m.shape) f.push(`shape=${str(m.shape)}`);
  if (m.shapeStyle) f.push(`shapeStyle=${str(m.shapeStyle)}`);
  if (m.direction) f.push(`direction=${str(m.direction)}`);
  if (m.flipbook) f.push(`flipbook={layout=${str(m.flipbook.layout)},mode=${str(m.flipbook.mode ?? 'Loop')}${m.flipbook.fps ? `,fps=${list(m.flipbook.fps)}` : ''}${m.flipbook.startRandom ? ',startRandom=true' : ''}}`);
  if (m.windAffectsDrag) f.push('windAffectsDrag=true');
  if (m.velocityInheritance !== undefined) f.push(`velocityInheritance=${num(m.velocityInheritance)}`);
  if (m.timeScale !== undefined) f.push(`timeScale=${num(m.timeScale)}`);
  if (m.offset) f.push(`offset=${list(m.offset)}`);
  if (m.turn) f.push(`turn=${list(m.turn)}`);
  if (m.detail && m.detail !== 'low') f.push(`detail=${str(m.detail)}`);
  return `{${f.join(',')}}`;
}

/** Tracks with their "tex:" textures resolved, as the JSON the runtime decodes. */
function timelineJson(tracks: TrackSpec[], tex: Resolve): string {
  const resolved = tracks.map((t) => {
    const copy = { ...t } as Record<string, unknown>;
    // A decal's size may be one number (a square): the runtime reads a pair.
    if (t.type === 'decal' && typeof t.size === 'number') copy.size = [t.size, t.size];
    for (const k of ['texture', 'textureId']) if (typeof copy[k] === 'string') copy[k] = tex(copy[k] as string) ?? copy[k];
    if (t.type === 'ribbon' && t.trail?.texture) copy.trail = { ...t.trail, texture: tex(t.trail.texture) ?? t.trail.texture };
    return copy;
  });
  return JSON.stringify(resolved);
}

function effectTable(e: EffectSpec, tex: Resolve): string {
  const { emitters, tracks } = compileEffect(e);
  const m = measureEffect(e);
  const radius = Math.round((m.bounds.radius + Math.hypot(...m.bounds.center)) * 10) / 10;
  const f = [`name=${str(e.name)}`, `kind=${str(e.kind)}`, `duration=${num(Math.max(e.duration ?? 0, e.kind === 'burst' ? m.duration : 0, 0.5))}`, `radius=${num(radius)}`];
  if (emitters.length) f.push(`emitters={${emitters.map((x) => emitterTable(x, tex)).join(',')}}`);
  if (tracks.length) f.push(`timeline=${longString(timelineJson(tracks, tex))}`);
  if (e.light) f.push(`light={color=${str(e.light.color)},brightness=${num(e.light.brightness)},range=${num(e.light.range)},duration=${num(e.light.duration)}}`);
  if (e.trail) {
    const t = e.trail;
    const texture = tex(t.texture);
    f.push(`trail={color=${strs(t.color)},transparency=${list(t.transparency)},width=${list(t.width)},lifetime=${num(t.lifetime)},lightEmission=${num(t.lightEmission ?? 0)},minLength=${num(t.minLength ?? 0.1)},faceCamera=${!!t.faceCamera}${texture ? `,texture=${str(texture)}` : ''}}`);
  }
  if (e.beam) {
    const b = e.beam;
    const texture = tex(b.texture);
    f.push(
      `beam={color=${strs(b.color)},transparency=${list(b.transparency)},width=${list(b.width)},lightEmission=${num(b.lightEmission ?? 0)},segments=${num(b.segments ?? 10)},curve=${list(b.curve ?? [0, 0])},faceCamera=${b.faceCamera !== false}${texture ? `,texture=${str(texture)},textureSpeed=${num(b.textureSpeed ?? 0)},textureLength=${num(b.textureLength ?? 1)}` : ''}}`,
    );
  }
  return `{${f.join(',')}}`;
}

