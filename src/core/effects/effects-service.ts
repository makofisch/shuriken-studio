/** world/Effects.luau: templates for every effect under ReplicatedStorage.ShurikenEffects (+ the relay remote, textures, cutscenes). */
export function effectsBuilder(effects: EffectSpec[], extras: BuilderExtras = {}): string {
  const tex: Resolve = (t) => {
    if (!t) return t;
    if (!t.startsWith('tex:')) return t;
    return extras.texture?.(t.slice(4)) ?? 'rbxasset://textures/particles/sparkles_main.dds';
  };
  const textures = Object.entries(extras.textures ?? {});
  const cutscenes = extras.cutscenes ?? [];
  return `-- Generated by Shuriken Studio from effects/*.fx.json (and effects/textures, effects/cutscenes). Do not edit: change the effects instead.
local ReplicatedStorage = game:GetService("ReplicatedStorage")
local HttpService = game:GetService("HttpService")
local EFFECTS = {
${effects.map((e) => `  ${effectTable(e, tex)},`).join('\n')}
}
local TEXTURES = {${textures.map(([n, id]) => `[${str(n)}]=${str(id)}`).join(',')}}
local CUTSCENES = {
${cutscenes.map((c) => `  {name=${str(c.name)},json=${longString(JSON.stringify(c))}},`).join('\n')}
}
local root = ReplicatedStorage:FindFirstChild("ShurikenEffects")
if not root then
  root = Instance.new("Folder")
  root.Name = "ShurikenEffects"
  root.Parent = ReplicatedStorage
end
if not root:FindFirstChild("Remote") then
  local r = Instance.new("RemoteEvent")
  r.Name = "Remote"
  r.Parent = root
end
local function nseq(k)
  if #k == 1 then return NumberSequence.new(k[1][2]) end
  local out = {}
  for _, p in k do table.insert(out, NumberSequenceKeypoint.new(p[1], p[2])) end
  return NumberSequence.new(out)
end
local function cseq(k)
  if #k == 1 then return ColorSequence.new(Color3.fromHex(k[1][2])) end
  local out = {}
  for _, p in k do table.insert(out, ColorSequenceKeypoint.new(p[1], Color3.fromHex(p[2]))) end
  return ColorSequence.new(out)
end
local function cseqList(v)
  if #v == 1 then return ColorSequence.new(Color3.fromHex(v[1])) end
  local k = {}
  for i, x in v do table.insert(k, ColorSequenceKeypoint.new((i - 1) / (#v - 1), Color3.fromHex(x))) end
  return ColorSequence.new(k)
end
local function nseqList(v)
  if #v == 1 then return NumberSequence.new(v[1]) end
  local k = {}
  for i, x in v do table.insert(k, NumberSequenceKeypoint.new((i - 1) / (#v - 1), x)) end
  return NumberSequence.new(k)
end
local notes = {}
-- Properties that a Studio version may not know: a failure is reported, not fatal.
local function try(fx, what, fn)
  local ok, err = pcall(fn)
  if not ok then table.insert(notes, fx .. ": " .. what .. ": " .. tostring(err)) end
end
local wanted = { Remote = true, Cutscenes = true }
local built, failed = {}, {}
for _, fx in EFFECTS do
  wanted[fx.name] = true
  local ok, err = pcall(function()
    local old = root:FindFirstChild(fx.name)
    if old then old:Destroy() end
    local tpl
    if fx.kind == "trail" then
      local t = fx.trail
      tpl = Instance.new("Trail")
      tpl.Color = cseqList(t.color)
      tpl.Transparency = nseqList(t.transparency)
      tpl.WidthScale = nseqList(t.width)
      tpl.Lifetime = t.lifetime
      tpl.LightEmission = t.lightEmission
      tpl.MinLength = t.minLength
      tpl.FaceCamera = t.faceCamera
      if t.texture then tpl.Texture = t.texture end
    elseif fx.kind == "beam" then
      local b = fx.beam
      tpl = Instance.new("Beam")
      tpl.Color = cseqList(b.color)
      tpl.Transparency = nseqList(b.transparency)
      tpl.Width0 = b.width[1]
      tpl.Width1 = b.width[2] or b.width[1]
      tpl.LightEmission = b.lightEmission
      tpl.Segments = b.segments
      tpl.CurveSize0 = b.curve[1]
      tpl.CurveSize1 = b.curve[2]
      tpl.FaceCamera = b.faceCamera
      if b.texture then
        tpl.Texture = b.texture
        tpl.TextureSpeed = b.textureSpeed
        tpl.TextureLength = b.textureLength
      end
    else
      tpl = Instance.new("Folder")
      for _, m in fx.emitters or {} do
        local e = Instance.new("ParticleEmitter")
        e.Name = m.name
        e.Texture = m.texture
        e.Color = cseq(m.color)
        e.Size = nseq(m.size)
        e.Transparency = nseq(m.transparency)
        e.Lifetime = NumberRange.new(m.lifetime[1], m.lifetime[2] or m.lifetime[1])
        e.Speed = NumberRange.new(m.speed[1], m.speed[2] or m.speed[1])
        if m.spread then e.SpreadAngle = Vector2.new(m.spread[1], m.spread[2] or m.spread[1]) end
        e.Rate = m.rate or 0
        if m.drag then e.Drag = m.drag end
        if m.acceleration then e.Acceleration = Vector3.new(m.acceleration[1], m.acceleration[2], m.acceleration[3]) end
        e.LightEmission = m.lightEmission or 0
        e.LightInfluence = m.lightInfluence or 0
        if m.rotation then e.Rotation = NumberRange.new(m.rotation[1], m.rotation[2] or m.rotation[1]) end
        if m.rotSpeed then e.RotSpeed = NumberRange.new(m.rotSpeed[1], m.rotSpeed[2] or m.rotSpeed[1]) end
        if m.orientation then e.Orientation = Enum.ParticleOrientation[m.orientation] end
        if m.zOffset then e.ZOffset = m.zOffset end
        if m.lockedToPart then e.LockedToPart = true end
        if m.shape then e.Shape = Enum.ParticleEmitterShape[m.shape] end
        if m.shapeStyle then e.ShapeStyle = Enum.ParticleEmitterShapeStyle[m.shapeStyle] end
        if m.direction then e.EmissionDirection = Enum.NormalId[m.direction] end
        if m.brightness then try(fx.name, "Brightness", function() e.Brightness = m.brightness end) end
        if m.squash then try(fx.name, "Squash", function() e.Squash = nseq(m.squash) end) end
        if m.flipbook then
          try(fx.name, "Flipbook", function()
            e.FlipbookLayout = Enum.ParticleFlipbookLayout[m.flipbook.layout]
            e.FlipbookMode = Enum.ParticleFlipbookMode[m.flipbook.mode]
            if m.flipbook.fps then e.FlipbookFramerate = NumberRange.new(m.flipbook.fps[1], m.flipbook.fps[2] or m.flipbook.fps[1]) end
            if m.flipbook.startRandom then e.FlipbookStartRandom = true end
          end)
        end
        if m.windAffectsDrag then try(fx.name, "WindAffectsDrag", function() e.WindAffectsDrag = true end) end
        if m.velocityInheritance then try(fx.name, "VelocityInheritance", function() e.VelocityInheritance = m.velocityInheritance end) end
        if m.timeScale then try(fx.name, "TimeScale", function() e.TimeScale = m.timeScale end) end
        e.Enabled = fx.kind == "persistent"
        e:SetAttribute("EmitCount", m.emit or 0)
        e:SetAttribute("EmitDelay", m.delay or 0)
        if m.emitFor then e:SetAttribute("EmitFor", m.emitFor) end
        if m.detail then e:SetAttribute("Detail", m.detail) end
        if m.offset then e:SetAttribute("Offset", Vector3.new(m.offset[1], m.offset[2], m.offset[3])) end
        if m.turn then e:SetAttribute("Turn", Vector3.new(m.turn[1], m.turn[2], m.turn[3])) end
        e.Parent = tpl
      end
      if fx.light then
        local l = Instance.new("PointLight")
        l.Name = "Light"
        l.Color = Color3.fromHex(fx.light.color)
        l.Brightness = fx.light.brightness
        l.Range = fx.light.range
        l.Shadows = false
        l:SetAttribute("FlashDuration", fx.light.duration)
        l.Parent = tpl
      end
      if fx.timeline then
        local v = Instance.new("StringValue")
        v.Name = "Timeline"
        v.Value = fx.timeline
        v.Parent = tpl
      end
    end
    tpl.Name = fx.name
    tpl:SetAttribute("Kind", fx.kind)
    tpl:SetAttribute("Duration", fx.duration)
    tpl:SetAttribute("Radius", fx.radius)
    tpl.Parent = root
    table.insert(built, fx.name)
  end)
  if not ok then table.insert(failed, { name = fx.name, error = tostring(err) }) end
end
for _, child in root:GetChildren() do
  if not wanted[child.Name] then child:Destroy() end
end
for name in root:GetAttributes() do
  if string.sub(name, 1, 8) == "Texture_" and not TEXTURES[string.sub(name, 9)] then root:SetAttribute(name, nil) end
end
for name, id in TEXTURES do root:SetAttribute("Texture_" .. name, id) end
local scenes = root:FindFirstChild("Cutscenes")
if #CUTSCENES == 0 then
  if scenes then scenes:Destroy() end
else
  if not scenes then
    scenes = Instance.new("Folder")
    scenes.Name = "Cutscenes"
    scenes.Parent = root
  end
  local keep = {}
  for _, c in CUTSCENES do
    keep[c.name] = true
    local v = scenes:FindFirstChild(c.name) or Instance.new("StringValue")
    v.Name = c.name
    v.Value = c.json
    v.Parent = scenes
  end
  for _, v in scenes:GetChildren() do
    if not keep[v.Name] then v:Destroy() end
  end
end
return HttpService:JSONEncode({ built = built, failed = failed, notes = notes })
`;
}

/** The Motion module from skill roblox-ui-motion's text (its first Luau block), or null when it isn't there. */
export function motionFromSkill(body: string | null | undefined): string | null {
  const block = body ? /```lua\r?\n([\s\S]*?)```/.exec(body)?.[1] : undefined;
  return block && /^--!strict\s*\n-- Motion:/.test(block) ? block : null;
}

