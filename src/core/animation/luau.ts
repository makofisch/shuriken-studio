import { R15_PARENT, clipDuration, type AnimationClip } from '@shared/animation';
import type { RigSpec } from '@shared/rig';

const num = (n: number) => String(Math.round(n * 10000) / 10000);
const str = (s: string) => JSON.stringify(s);
/**
 * Roblox's legacy Cubic runs its In/Out backwards (measured: Cubic "In" starts fast), CubicV2 matches
 * TweenService like the clip format does, so Cubic is written as CubicV2.
 */
const robloxEase = (e: string | undefined) => (e === 'Cubic' ? 'CubicV2' : (e ?? 'Linear'));

const deg = (n: number) => String(Math.round(n * 100) / 100);
const studs = (n: number) => String(Math.round(n * 1000) / 1000);

/**
 * One clip as a Luau table literal (the builder's data), kept compact so the file stays readable in
 * size: rotations to 0.01°, positions to 0.001 studs, and the easing written once per key (a pose
 * only repeats it when it differs).
 */
function clipTable(c: AnimationClip, asset: string | undefined, rig?: RigSpec): string {
  const keys = c.keys
    .map((k) => {
      const entries = Object.entries(k.poses);
      // The key's usual easing: the most common among its poses.
      const tally = new Map<string, number>();
      for (const [, p] of entries) {
        const e = `${robloxEase(p!.ease)}/${p!.dir ?? 'InOut'}`;
        tally.set(e, (tally.get(e) ?? 0) + 1);
      }
      const common = [...tally.entries()].sort((a, b) => b[1] - a[1])[0]?.[0] ?? 'Linear/InOut';
      const [ke, kd] = common.split('/') as [string, string];
      const poses = entries
        .map(([j, p]) => {
          const parts = [`r={${(p!.rot ?? [0, 0, 0]).map(deg).join(',')}}`];
          if (p!.pos) parts.push(`p={${p!.pos.map(studs).join(',')}}`);
          if (robloxEase(p!.ease) !== ke) parts.push(`e=${str(robloxEase(p!.ease))}`);
          if ((p!.dir ?? 'InOut') !== kd) parts.push(`d=${str(p!.dir ?? 'InOut')}`);
          return `[${str(j)}]={${parts.join(',')}}`;
        })
        .join(',');
      return `{t=${num(k.t)},e=${str(ke)},d=${str(kd)},poses={${poses}}}`;
    })
    .join(',');
  const markers = (c.markers ?? []).map((m) => `{t=${num(m.t)},name=${str(m.name)},value=${str(m.value ?? '')}}`).join(',');
  // A custom rig's poses nest along its joints, its root joint under the rig's HumanoidRootPart.
  const par = rig ? `,par={${rig.joints.map((j) => `[${str(j.name)}]=${str(j.parent ?? 'HumanoidRootPart')}`).join(',')}}` : '';
  return `{name=${str(c.name)},loop=${c.loop},priority=${str(c.priority)},duration=${num(clipDuration(c))},asset=${asset ? str(asset) : 'nil'},keys={${keys}},markers={${markers}}${par}}`;
}

/**
 * world/Animations.luau: builds every clip of the project as a KeyframeSequence under
 * ReplicatedStorage.ShurikenAnimations.Sequences, with an Animation object per clip next to it
 * (AnimationId: the uploaded asset when the clip has a current one, otherwise a Studio-local id; the
 * AssetId attribute tells the runtime module which). Idempotent, like every world builder.
 */
export function animationsBuilder(clips: AnimationClip[], assets: Record<string, string> = {}, rigs: Record<string, RigSpec> = {}): string {
  const parents = Object.entries(R15_PARENT)
    .map(([j, p]) => `${j}=${str(p)}`)
    .join(',');
  return `-- Generated by Shuriken Studio from animations/*.anim.json. Do not edit: change the clips instead.
local ReplicatedStorage = game:GetService("ReplicatedStorage")
local KSP = game:GetService("KeyframeSequenceProvider")
local HttpService = game:GetService("HttpService")
local PARENT = {${parents}}
local CLIPS = {
${clips.map((c) => `  ${clipTable(c, assets[c.name], c.rig ? rigs[c.rig] : undefined)},`).join('\n')}
}
local root = ReplicatedStorage:FindFirstChild("ShurikenAnimations")
if not root then
  root = Instance.new("Folder")
  root.Name = "ShurikenAnimations"
  root.Parent = ReplicatedStorage
end
local seqs = root:FindFirstChild("Sequences")
if not seqs then
  seqs = Instance.new("Folder")
  seqs.Name = "Sequences"
  seqs.Parent = root
end
local wanted = {}
local function cf(r, p)
  local c = CFrame.new()
  if p then c = CFrame.new(p[1], p[2], p[3]) end
  if r then c = c * CFrame.Angles(math.rad(r[1]), math.rad(r[2]), math.rad(r[3])) end
  return c
end
local built, failed = {}, {}
for _, clip in CLIPS do
 local ok, err = pcall(function()
  wanted[clip.name] = true
  local old = seqs:FindFirstChild(clip.name)
  if old then old:Destroy() end
  local kfs = Instance.new("KeyframeSequence")
  kfs.Name = clip.name
  kfs.Loop = clip.loop
  kfs.Priority = Enum.AnimationPriority[clip.priority]
  if not clip.par then kfs.AuthoredHipHeight = 2.1924 end
  local frames = {}
  for _, key in clip.keys do
    local k = Instance.new("Keyframe")
    k.Time = key.t
    local made = {}
    local function pose(name)
      if made[name] then return made[name] end
      local p = Instance.new("Pose")
      p.Name = name
      p.Weight = 0
      local parentName = if clip.par then clip.par[name] else PARENT[name]
      if parentName == "HumanoidRootPart" or parentName == nil then
        if name == "HumanoidRootPart" then
          p.Parent = k
        else
          p.Parent = pose("HumanoidRootPart")
        end
      else
        p.Parent = pose(parentName)
      end
      made[name] = p
      return p
    end
    for joint, v in key.poses do
      local p = pose(joint)
      p.Weight = 1
      p.CFrame = cf(v.r, v.p)
      p.EasingStyle = Enum.PoseEasingStyle[v.e or key.e] or Enum.PoseEasingStyle.Linear
      p.EasingDirection = Enum.PoseEasingDirection[v.d or key.d] or Enum.PoseEasingDirection.InOut
    end
    k.Parent = kfs
    table.insert(frames, k)
  end
  for _, m in clip.markers do
    local host = nil
    for _, k in frames do
      if math.abs(k.Time - m.t) < 0.001 then host = k break end
    end
    if not host then
      host = Instance.new("Keyframe")
      host.Time = m.t
      host.Parent = kfs
    end
    local mk = Instance.new("KeyframeMarker")
    mk.Name = m.name
    mk.Value = m.value
    mk.Parent = host
  end
  kfs:SetAttribute("Duration", clip.duration)
  kfs.Parent = seqs
  local anim = root:FindFirstChild(clip.name)
  if not (anim and anim:IsA("Animation")) then
    if anim then anim:Destroy() end
    anim = Instance.new("Animation")
    anim.Name = clip.name
    anim.Parent = root
  end
  anim:SetAttribute("AssetId", clip.asset)
  anim:SetAttribute("Duration", clip.duration)
  if clip.asset then
    anim.AnimationId = "rbxassetid://" .. clip.asset
  else
    anim.AnimationId = KSP:RegisterKeyframeSequence(kfs)
  end
  table.insert(built, { name = clip.name, id = anim.AnimationId })
 end)
 if not ok then table.insert(failed, { name = clip.name, error = tostring(err) }) end
end
for _, child in seqs:GetChildren() do
  if not wanted[child.Name] then child:Destroy() end
end
for _, child in root:GetChildren() do
  if child:IsA("Animation") and not wanted[child.Name] then child:Destroy() end
end
return HttpService:JSONEncode({ built = built, failed = failed })
`;
}

