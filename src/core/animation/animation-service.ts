import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { clipDuration, clipJointNames, resolveAims, validateClip, type AnimationClip } from '@shared/animation';
import type { RigSpec } from '@shared/rig';
import type { AnimationSummary } from '@shared/domain';
import { DEFAULT_SYNC_MAP, type SyncMap } from '../roblox/luau-toolchain';
import { animationsBuilder, RUNTIME_MODULE, RUNTIME_VERSION } from './luau';
import type { PresetParams } from './presets';
import { ModelStore } from '../modeling/model-store';
import type { KilnSource } from './kiln-clips';
import { LEGACY_OWNER } from '../roblox/upload-owner';

export const ANIM_DIR = 'animations';
export const BUILDER_REL = 'world/Animations.luau';
const RUNTIME_MARKER = /^-- ShurikenAnimations v(\d+) \(generated by Shuriken Studio/m;

/** animations/<Name>.anim.json: the source of truth for one clip. */
export interface AnimationFile {
  clip: AnimationClip;
  /** The preset (and its parameters) the clip came from, when it came from one. */
  preset?: string;
  params?: PresetParams;
  createdBy?: string;
  updatedAt: string;
  /** Uploaded Roblox asset, valid while the clip's hash matches. */
  upload?: { assetId: string; hash: string; at: string; owner?: string };
  /**
   * Roblox took the upload of this version of the clip and is still processing it (the Open Cloud operation
   * id): the next upload asks about it instead of sending the clip again. Valid while the hash matches.
   */
  uploading?: { operation: string; hash: string; at: string; owner?: string };
  /** Made in Kiln (a rigged model's clip): the next export of that model updates or removes it. */
  source?: KilnSource;
  /** Brought in from the game's own animation (a KeyframeSequence path or an asset id). */
  imported?: { from: string; at: string };
  /** Made in the Animation dock to try out: plays in Shuriken, and is not in the game until "Add to game" (animation_use). */
  draft?: boolean;
  /** A draft that is a new take of this animation of the game (it got the next free name instead of replacing it). */
  draftOf?: string;
}

/** A clip's problems; a custom rig's clip is checked against its rig (and is unusable without it). */
function problems(c: AnimationClip, rigs: Record<string, RigSpec>): string[] {
  return c.rig ? validateClip(c, rigs[c.rig] ?? null) : validateClip(c);
}

export function clipHash(c: AnimationClip): string {
  const { description: _d, ...rest } = c;
  return createHash('sha1').update(JSON.stringify(rest)).digest('hex').slice(0, 12);
}

/**
 * The project's animations on disk and the generated files that put them into the place: the world
 * builder (KeyframeSequences + Animation objects in ReplicatedStorage.ShurikenAnimations) and the
 * runtime module games use to play them.
 */
export class AnimationStore {
  constructor(private readonly root: string) {}

  private dir(): string {
    return join(this.root, ANIM_DIR);
  }

  private file(name: string): string {
    return join(this.dir(), `${name}.anim.json`);
  }

  names(): string[] {
    if (!existsSync(this.dir())) return [];
    return readdirSync(this.dir())
      .filter((f) => f.endsWith('.anim.json'))
      .map((f) => f.slice(0, -'.anim.json'.length))
      .sort((a, b) => a.localeCompare(b));
  }

  get(name: string): AnimationFile | null {
    const f = this.file(name);
    if (!existsSync(f)) return null;
    try {
      return JSON.parse(readFileSync(f, 'utf8')) as AnimationFile;
    } catch {
      return null;
    }
  }

  all(): AnimationFile[] {
    const rigs = new ModelStore(this.root).rigs();
    return this.names()
      .map((n) => this.get(n))
      .filter((f): f is AnimationFile => !!f && problems(f.clip, rigs).length === 0);
  }

  /** The game's animations: everything but the dock's drafts. */
  inGame(): AnimationFile[] {
    return this.all().filter((f) => !f.draft);
  }

  /** `name`, or the next free name after it when an animation of the game already has it (a draft never replaces one). */
  freeName(name: string): string {
    const taken = (n: string) => {
      const f = this.get(n);
      return !!f && !f.draft;
    };
    if (!taken(name)) return name;
    // Slash1 → Slash1_2 (Slash12 would read as another hit of the combo).
    const stem = /\d$/.test(name) ? `${name}_` : name;
    for (let i = 2; i < 100; i++) if (!this.get(`${stem}${i}`)) return `${stem}${i}`;
    return `${stem}${Date.now().toString(36)}`;
  }

  /**
   * Puts a draft in the game: under its own name, or as `as` (replacing that animation with this take).
   * Null when there is no such animation; the place follows with the next build.
   */
  use(name: string, as?: string): AnimationFile | null {
    const f = this.get(name);
    if (!f) return null;
    const target = as?.trim() || f.clip.name;
    const { draft: _draft, draftOf: _of, updatedAt: _at, upload: _upload, uploading: _uploading, ...rest } = f;
    if (target !== f.clip.name) rmSync(this.file(name));
    return this.save({ ...rest, clip: { ...f.clip, name: target } });
  }

  /** Problems with files that can't be built (bad JSON, an invalid clip, or a custom rig's clip without its rig). */
  broken(): Array<{ name: string; problems: string[] }> {
    const rigs = new ModelStore(this.root).rigs();
    const out: Array<{ name: string; problems: string[] }> = [];
    for (const n of this.names()) {
      const f = this.get(n);
      if (!f) out.push({ name: n, problems: ['not valid JSON'] });
      else {
        const p = problems(f.clip, rigs);
        if (p.length) out.push({ name: n, problems: p });
      }
    }
    return out;
  }

  /** Saves a clip (validated by the caller) and regenerates the builder; keeps a still-valid upload. */
  save(entry: Omit<AnimationFile, 'updatedAt' | 'upload' | 'uploading'>): AnimationFile {
    mkdirSync(this.dir(), { recursive: true });
    const prev = this.get(entry.clip.name);
    const hash = clipHash(entry.clip);
    const file: AnimationFile = {
      ...entry,
      updatedAt: new Date().toISOString(),
      ...(prev?.upload && prev.upload.hash === hash ? { upload: prev.upload } : {}),
      ...(prev?.uploading && prev.uploading.hash === hash ? { uploading: prev.uploading } : {}),
    };
    writeFileSync(this.file(entry.clip.name), `${JSON.stringify(file, null, 2)}\n`, 'utf8');
    this.writeBuilder();
    return file;
  }

  /** Records an uploaded asset id for the clip's current content. */
  setUpload(name: string, assetId: string, owner?: string): AnimationFile {
    const f = this.get(name);
    if (!f) throw new Error(`No animation named ${name}`);
    const { uploading: _processing, ...rest } = f;
    const next: AnimationFile = { ...rest, upload: { assetId, hash: clipHash(f.clip), at: new Date().toISOString(), ...(owner && owner !== LEGACY_OWNER ? { owner } : {}) } };
    writeFileSync(this.file(name), `${JSON.stringify(next, null, 2)}\n`, 'utf8');
    this.writeBuilder();
    return next;
  }

  /** Records the Open Cloud operation of an upload of the clip's current version that Roblox is still processing. */
  setUploading(name: string, operation: string, owner?: string): AnimationFile {
    const f = this.get(name);
    if (!f) throw new Error(`No animation named ${name}`);
    const next: AnimationFile = { ...f, uploading: { operation, hash: clipHash(f.clip), at: new Date().toISOString(), ...(owner && owner !== LEGACY_OWNER ? { owner } : {}) } };
    writeFileSync(this.file(name), `${JSON.stringify(next, null, 2)}\n`, 'utf8');
    return next;
  }

  /** The operation Roblox is still processing for the clip's current version, if any. */
  /** An upload of this version still being processed, for `owner` (a clip uploaded for another owner is sent again). */
  static pendingOperation(f: AnimationFile, owner: string = LEGACY_OWNER): string | null {
    return f.uploading && f.uploading.hash === clipHash(f.clip) && (f.uploading.owner ?? LEGACY_OWNER) === owner ? f.uploading.operation : null;
  }

  remove(name: string): boolean {
    const f = this.file(name);
    if (!existsSync(f)) return false;
    rmSync(f);
    this.writeBuilder();
    return true;
  }

  /**
   * world/Animations.luau regenerated from the clips as they are now, written only when it differs from
   * the file on disk. True when it changed: the place's animations are out of date (a changed clip, or
   * the rig its poses nest along) and need a rebuild.
   */
  refreshBuilder(): boolean {
    const path = join(this.root, BUILDER_REL);
    const before = existsSync(path) ? readFileSync(path, 'utf8') : '';
    return this.writeBuilder() !== before;
  }

  /** world/Animations.luau from every valid clip of the game (drafts stay out; deleted when there are none). */
  writeBuilder(): string {
    const files = this.inGame();
    const path = join(this.root, BUILDER_REL);
    if (!files.length) {
      if (existsSync(path)) rmSync(path);
      return '';
    }
    // A clip for a custom rig builds only while its rig exists (models/<Model>.rig.json; all() checks).
    const rigs = new ModelStore(this.root).rigs();
    const code = animationsBuilder(files.map((f) => (f.clip.rig ? f.clip : resolveAims(f.clip))), Object.fromEntries(files.filter((f) => f.upload && f.upload.hash === clipHash(f.clip)).map((f) => [f.clip.name, f.upload!.assetId])), rigs);
    mkdirSync(join(this.root, 'world'), { recursive: true });
    writeFileSync(path, code, 'utf8');
    return code;
  }

  /** Where the runtime module goes: the synced folder that maps into ReplicatedStorage. */
  static runtimeLocation(syncMap: SyncMap | undefined): { file: string; requirePath: string } {
    const map = syncMap && Object.keys(syncMap).length ? syncMap : DEFAULT_SYNC_MAP;
    const entry = Object.entries(map).find(([, inst]) => inst === 'ReplicatedStorage' || inst.startsWith('ReplicatedStorage/')) ?? ['src/Shared', 'ReplicatedStorage/Shared'];
    const segs = entry[1].split('/').slice(1);
    return {
      file: `${entry[0].replace(/\/$/, '')}/ShurikenAnimations.luau`,
      requirePath: ['game.ReplicatedStorage', ...segs.map((s) => (/^[A-Za-z_]\w*$/.test(s) ? s : `[${JSON.stringify(s)}]`)), 'ShurikenAnimations'].join('.').replace(/\.\[/g, '['),
    };
  }

  /** Writes the runtime module when it's missing or older; leaves a hand-replaced module alone. */
  ensureRuntime(syncMap: SyncMap | undefined): { file: string; requirePath: string; written: boolean } {
    const loc = AnimationStore.runtimeLocation(syncMap);
    const path = join(this.root, loc.file);
    if (existsSync(path)) {
      const m = RUNTIME_MARKER.exec(readFileSync(path, 'utf8'));
      if (!m || Number(m[1]) >= RUNTIME_VERSION) return { ...loc, written: false };
    }
    mkdirSync(join(path, '..'), { recursive: true });
    writeFileSync(path, RUNTIME_MODULE, 'utf8');
    return { ...loc, written: true };
  }

  summary(f: AnimationFile): AnimationSummary {
    const hash = clipHash(f.clip);
    return {
      name: f.clip.name,
      description: f.clip.description ?? '',
      loop: f.clip.loop,
      priority: f.clip.priority,
      duration: clipDuration(f.clip),
      keys: f.clip.keys.length,
      joints: clipJointNames(f.clip).length,
      markers: (f.clip.markers ?? []).map((m) => ({ name: m.name, t: m.t })),
      preset: f.preset ?? null,
      rig: f.clip.rig ?? null,
      uploaded: f.upload && f.upload.hash === hash ? f.upload.assetId : null,
      updatedAt: f.updatedAt,
      ...(f.source?.kind === 'kiln' ? { kiln: { model: f.source.model, clip: f.source.clip, speed: f.source.speed, inPlace: f.source.inPlace } } : {}),
      ...(f.draft ? { draft: true, ...(f.draftOf ? { draftOf: f.draftOf } : {}) } : {}),
    };
  }
}
