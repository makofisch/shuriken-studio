export const SOUND_DIR = 'audio';
export const AUDIO_BUILDER_REL = 'world/Audio.luau';
export const AUDIO_CREDITS_REL = `${SOUND_DIR}/CREDITS.md`;
export const AUDIO_RUNTIME_VERSION = 2;
const RUNTIME_MARKER = /^-- ShurikenAudio v(\d+) \(generated by Shuriken Studio/m;

/**
 * Where an imported track came from and the license it is used under: kept with the sound, and listed in
 * audio/CREDITS.md (CC BY and CC BY-SA ask for a credit wherever the game credits its sources).
 */
export interface SoundCredit {
  title: string;
  creator: string;
  creatorUrl?: string;
  /** cc0, pdm, by or by-sa (sourcing.ts COMMERCIAL_LICENSES). */
  license: string;
  /** "CC BY 4.0" */
  licenseName: string;
  licenseUrl?: string;
  /** The page the track is on. */
  sourceUrl: string;
  downloadUrl: string;
  /** A ready credit line for a Credits screen or the game's description. */
  attribution: string;
  /** The site (freesound, jamendo, wikimedia_audio...). */
  origin?: string;
  importedAt: string;
}

/** A sample a composed song plays, and where it came from. */
export interface SampleUse {
  id: string;
  name: string;
  source: 'web' | 'user' | 'builtin';
  /** Web samples: cc0 or pdm, the creator and the page. */
  license?: string;
  licenseName?: string;
  creator?: string;
  sourceUrl?: string;
}

/** audio/<Name>.sound.json: one of the game's sounds (generated here, imported from the web, or from the Creator Store). */
export interface SoundEntry {
  name: string;
  kind: 'sfx' | 'music' | 'ambience';
  /** generated: made by the synthesizer; imported: a licensed web track saved under assets/audio (see credit); store: a Creator Store asset id. */
  source: 'generated' | 'imported' | 'store';
  /** Roblox asset id once uploaded (or the Creator Store id). */
  assetId: string | null;
  /** Who the upload went to (upload-owner.ts ownerKey; unset: the person). Another owner uploads it again. */
  assetOwner?: string;
  /** The generated or imported file (project-relative). */
  file?: string;
  /** Imported tracks: the source, creator and license (audio/CREDITS.md lists them). */
  credit?: SoundCredit;
  /** Composed songs: the samples they play (web samples are CC0 or public domain; audio/CREDITS.md lists them anyway). */
  samples?: SampleUse[];
  /** Alternative takes of a generated effect, played at random so repeats don't sound robotic. */
  variations?: Array<{ file: string; assetId: string | null; assetOwner?: string }>;
  /** Roblox Sound.Volume (0–10; 0.5 is a good default). */
  volume: number;
  looped: boolean;
  /** Random pitch spread for effects (0.06 = ±6 %). */
  pitchVariation?: number;
  /** Distance (studs) a 3D sound fades out over. */
  range?: number;
  description?: string;
  preset?: string;
  style?: string;
  /** Loudness class a generated sound was mastered to (dsp/master LOUDNESS_TARGETS). */
  category?: string;
  /**
   * Looped generated MP3s: where the audio sits in the decoded file, in seconds (the encoder delay is
   * skipped at the start, the padding after the end). The builder turns it into Sound.LoopRegion.
   */
  loop?: { start: number; length: number };
  /** The mastering gate's one-line summary (peak, loudness, DC...), for the dock and the director. */
  check?: string;
  durationSec?: number;
  /** The last upload attempt that did not produce an asset id. */
  upload?: { operation?: string; error?: string; at: string };
  /**
   * Made in the Audio dock to try out (by the user or its copilot): kept here to listen to, not built
   * into the game or uploaded until it's added (audio_use, the dock's "Add to game").
   */
  draft?: boolean;
  asset?: string;
  updatedAt: string;
}

const str = (s: string) => JSON.stringify(s);
const num = (n: number) => String(Math.round(n * 1000) / 1000);
/** Loop positions are sample-accurate seconds: more digits than the volumes above. */
const loopNum = (n: number) => String(Math.round(n * 1e6) / 1e6);

export function audioBuilder(sounds: SoundEntry[]): string {
  const rows = sounds.map((s) => {
    const alts = (s.variations ?? []).map((v) => v.assetId).filter((x): x is string => !!x);
    // Only looped sounds with a known region carry one (a Store sound has no encoder delay we know of).
    const loop = s.looped && s.loop && s.loop.length > 0 ? `,loopStart=${loopNum(s.loop.start)},loopLength=${loopNum(s.loop.length)}` : '';
    return `  {name=${str(s.name)},kind=${str(s.kind)},id=${s.assetId ? str(s.assetId) : 'nil'},volume=${num(s.volume)},looped=${s.looped},pitch=${num(s.pitchVariation ?? 0)},range=${num(s.range ?? 80)},alts=${str(alts.join(','))}${loop}},`;
  });
  return `-- Generated by Shuriken Studio from audio/*.sound.json. Do not edit: change the sounds instead.
local ReplicatedStorage = game:GetService("ReplicatedStorage")
local SoundService = game:GetService("SoundService")
local HttpService = game:GetService("HttpService")
local SOUNDS = {
${rows.join('\n')}
}
local function group(name, volume)
  local g = SoundService:FindFirstChild(name)
  if not g then
    g = Instance.new("SoundGroup")
    g.Name = name
    g.Volume = volume
    g.Parent = SoundService
  end
  return g
end
local groups = { sfx = group("ShurikenSFX", 1), music = group("ShurikenMusic", 0.7), ambience = group("ShurikenAmbience", 0.8) }
local root = ReplicatedStorage:FindFirstChild("ShurikenAudio")
if not root then
  root = Instance.new("Folder")
  root.Name = "ShurikenAudio"
  root.Parent = ReplicatedStorage
end
local wanted, built, missing = {}, {}, {}
for _, s in SOUNDS do
  wanted[s.name] = true
  local snd = root:FindFirstChild(s.name)
  if not (snd and snd:IsA("Sound")) then
    if snd then snd:Destroy() end
    snd = Instance.new("Sound")
    snd.Name = s.name
    snd.Parent = root
  end
  snd.SoundId = s.id and ("rbxassetid://" .. s.id) or ""
  snd.Volume = s.volume
  snd.Looped = s.looped
  snd.RollOffMaxDistance = s.range
  snd.RollOffMode = Enum.RollOffMode.InverseTapered
  snd.SoundGroup = groups[s.kind]
  -- Generated loops are MP3s without a gapless tag: a decoder plays the encoder delay first and padding
  -- after the audio, which is a 50-70 ms gap at every wrap. The loop region skips both.
  -- NEEDS A STUDIO CHECK (Sound.PlaybackRegionsEnabled / LoopRegion behaviour is not measured yet), so a
  -- Studio without these properties just keeps the plain loop instead of failing the build.
  pcall(function()
    if s.loopLength then
      snd.PlaybackRegionsEnabled = true
      snd.LoopRegion = NumberRange.new(s.loopStart or 0, (s.loopStart or 0) + s.loopLength)
    else
      snd.PlaybackRegionsEnabled = false
    end
  end)
  snd:SetAttribute("Kind", s.kind)
  snd:SetAttribute("PitchVariation", s.pitch)
  snd:SetAttribute("Variations", s.alts)
  table.insert(built, s.name)
  if not s.id then table.insert(missing, s.name) end
end
for _, c in root:GetChildren() do
  if not wanted[c.Name] then c:Destroy() end
end
return HttpService:JSONEncode({ built = built, notUploaded = missing })
`;
}

const mmss = (sec: number) => `${Math.floor(sec / 60)}:${String(Math.round(sec % 60)).padStart(2, '0')}`;

/**
 * audio/CREDITS.md: every imported sound's title, creator, license and URL, and the web and user samples the
 * composed songs play ('' when there are none).
 */
export function creditsMarkdown(sounds: SoundEntry[]): string {
  const imported = sounds.filter((s) => s.credit);
  const sampled = sounds.filter((s) => s.samples?.some((u) => u.source !== 'builtin'));
  if (!imported.length && !sampled.length) return '';
  const lines = [
    '# Audio credits',
    '',
    "Sounds in this game that come from the web, not from Shuriken's synthesizer or the Creator Store. CC BY and CC BY-SA ask for a credit: put the credit lines below where the game credits its sources (a Credits screen, the game's description). CC0 and public domain need none. Written by Shuriken Studio; change the sounds, not this file.",
  ];
  for (const s of imported) {
    const c = s.credit!;
    const needs = c.license === 'by' || c.license === 'by-sa';
    lines.push(
      '',
      `## ${s.name} (${s.kind}${s.durationSec !== undefined ? `, ${mmss(s.durationSec)}` : ''})${s.draft ? ' - a draft, not in the game yet' : ''}`,
      `- Title: ${c.title}`,
      `- Creator: ${c.creator}${c.creatorUrl ? ` (${c.creatorUrl})` : ''}`,
      `- License: ${c.licenseName}${c.licenseUrl ? ` (${c.licenseUrl})` : ''} - ${needs ? 'credit required' : 'no credit required'}${c.license === 'by-sa' ? '; adaptations of the sound must stay CC BY-SA' : ''}`,
      `- Source: ${c.sourceUrl}`,
      `- Credit line: ${c.attribution}`,
    );
  }
  if (sampled.length) {
    lines.push('', '## Samples in composed songs', '', "Web samples are CC0 or public domain only (no credit required; listed so their source is known). The user's own samples are theirs to have the rights to.");
    for (const s of sampled) {
      lines.push('', `### ${s.name}${s.draft ? ' - a draft, not in the game yet' : ''}`);
      for (const u of s.samples!.filter((x) => x.source !== 'builtin'))
        lines.push(u.source === 'web' ? `- ${u.name} (${u.id}): ${u.creator ?? 'unknown'}, ${u.licenseName ?? u.license ?? 'CC0'}, ${u.sourceUrl ?? ''}`.trimEnd() : `- ${u.name} (${u.id}): the user's own sample`);
    }
  }
  return `${lines.join('\n')}\n`;
}

/**
 * A function whose name says it plays a sound: play*, loop*, or *audio* / *sound* / *sfx* / *music* (not
 * "display"), and not an animation's (Anims.play("Jump") plays a clip).
 */
const PLAYS = '(?<!anim\\w*\\s*[.:]\\s*)\\b(?:\\w*(?:audio|sound|sfx|music)\\w*|play\\w*|loop\\w*)';

export const AUDIO_RUNTIME_MODULE = `--!strict
-- ShurikenAudio v2 (generated by Shuriken Studio; safe to use, don't edit).
-- Plays the game's sounds by name (templates in ReplicatedStorage.ShurikenAudio):
--   local Audio = require(game.ReplicatedStorage.Shared.ShurikenAudio)
--   Audio.play("SwordSwing")                 -- 2D (UI, the local player's own actions)
--   Audio.play("SwordHit", hitPosition)      -- 3D at a Vector3/CFrame, or following a part/attachment
--   Audio.music("BattleTheme")               -- crossfades to a looping track; Audio.stopMusic()
-- Effects get a little random pitch (and a random take when there are several), so repeats sound natural.
local ReplicatedStorage = game:GetService("ReplicatedStorage")
local SoundService = game:GetService("SoundService")
local RunService = game:GetService("RunService")
local TweenService = game:GetService("TweenService")
local Debris = game:GetService("Debris")

export type PlayOptions = { volume: number?, pitch: number? }

local Audio = {}
local root = ReplicatedStorage:WaitForChild("ShurikenAudio")
local warned: { [string]: boolean } = {}
local current: Sound? = nil
local rng = Random.new()

local function template(name: string): Sound?
	local s = root:FindFirstChild(name)
	if not (s and s:IsA("Sound")) then
		if not warned[name] then
			warned[name] = true
			warn(("[ShurikenAudio] no sound named %s"):format(name))
		end
		return nil
	end
	if s.SoundId == "" then
		if not warned[name] then
			warned[name] = true
			warn(("[ShurikenAudio] %s isn't uploaded yet, so it is silent"):format(name))
		end
		return nil
	end
	return s
end

local function cleanup(s: Sound)
	s.Ended:Once(function()
		s:Destroy()
	end)
	Debris:AddItem(s, math.max(1, s.TimeLength / math.max(0.1, s.PlaybackSpeed)) + 2)
end

local function globalParent(): Instance
	return if RunService:IsClient() then SoundService else workspace
end

--- Plays a sound: 2D without \`where\`, 3D at a position or on a part/attachment. Returns the Sound.
function Audio.play(name: string, where: any?, opts: PlayOptions?): Sound?
	local tpl = template(name)
	if not tpl then
		return nil
	end
	local s = tpl:Clone()
	local alts = tpl:GetAttribute("Variations")
	if typeof(alts) == "string" and alts ~= "" then
		local choices = string.split(alts, ",")
		local pick = rng:NextInteger(0, #choices)
		if pick > 0 then
			s.SoundId = "rbxassetid://" .. choices[pick]
		end
	end
	local spreadValue = tpl:GetAttribute("PitchVariation")
	local spread = if typeof(spreadValue) == "number" then spreadValue else 0
	local pitch = if opts and opts.pitch then opts.pitch else 1
	local jitter = if spread > 0 then rng:NextNumber(-spread, spread) else 0
	s.PlaybackSpeed = pitch * (1 + jitter)
	if opts and opts.volume then
		s.Volume = opts.volume
	end
	local at: any = where
	local kind = typeof(at)
	if kind == "Vector3" or kind == "CFrame" then
		local a = Instance.new("Attachment")
		a.Name = "ShurikenSound"
		if kind == "Vector3" then
			a.WorldPosition = at
		else
			a.WorldCFrame = at
		end
		a.Parent = workspace.Terrain
		s.Parent = a
		Debris:AddItem(a, math.max(1, s.TimeLength) + 3)
	elseif kind == "Instance" and (at:IsA("BasePart") or at:IsA("Attachment")) then
		s.Parent = at
	else
		s.Parent = globalParent()
	end
	s:Play()
	if not s.Looped then
		cleanup(s)
	end
	return s
end

--- Crossfades to a looping music track (one plays at a time). Returns the Sound.
function Audio.music(name: string, fade: number?): Sound?
	local playing = current
	if playing and playing.Name == name and playing.IsPlaying then
		return playing
	end
	local tpl = template(name)
	if not tpl then
		return nil
	end
	local f = fade or 1.5
	local s = tpl:Clone()
	s.Looped = true
	local target = s.Volume
	s.Volume = 0
	s.Parent = globalParent()
	s:Play()
	TweenService:Create(s, TweenInfo.new(f), { Volume = target }):Play()
	if playing then
		local old: Sound = playing
		TweenService:Create(old, TweenInfo.new(f), { Volume = 0 }):Play()
		task.delay(f, function()
			old:Destroy()
		end)
	end
	current = s
	return s
end

function Audio.stopMusic(fade: number?)
	local playing = current
	if not playing then
		return
	end
	current = nil
	local old: Sound = playing
	local f = fade or 1.5
	TweenService:Create(old, TweenInfo.new(f), { Volume = 0 }):Play()
	task.delay(f, function()
		old:Destroy()
	end)
end

--- The template Sound (to configure your own copies).
function Audio.get(name: string): Sound?
	return template(name)
end

return Audio
`;

/** Which sounds a script plays, by file: valid while the file (time and size) and the sound list are the same. */
const USAGE_CACHE = new Map<string, { stamp: string; sounds: string; names: string[] }>();

export class SoundLibrary {
  constructor(private readonly root: string) {}

  private dir(): string {
    return join(this.root, SOUND_DIR);
  }

  names(): string[] {
    if (!existsSync(this.dir())) return [];
    return readdirSync(this.dir())
      .filter((f) => f.endsWith('.sound.json'))
      .map((f) => f.slice(0, -'.sound.json'.length))
      .sort((a, b) => a.localeCompare(b));
  }

  get(name: string): SoundEntry | null {
    const f = join(this.dir(), `${name}.sound.json`);
    if (!existsSync(f)) return null;
    try {
      return JSON.parse(readFileSync(f, 'utf8')) as SoundEntry;
    } catch {
      return null;
    }
  }

  all(): SoundEntry[] {
    return this.names()
      .map((n) => this.get(n))
      .filter((s): s is SoundEntry => !!s);
  }

  save(entry: Omit<SoundEntry, 'updatedAt'>): SoundEntry {
    mkdirSync(this.dir(), { recursive: true });
    const s: SoundEntry = { ...entry, updatedAt: new Date().toISOString() };
    writeFileSync(join(this.dir(), `${entry.name}.sound.json`), `${JSON.stringify(s, null, 2)}\n`, 'utf8');
    this.writeBuilder();
    this.writeCredits();
    return s;
  }

  remove(name: string): boolean {
    const f = join(this.dir(), `${name}.sound.json`);
    if (!existsSync(f)) return false;
    rmSync(f);
    this.writeBuilder();
    this.writeCredits();
    return true;
  }

  /** The game's sounds: everything but drafts. */
  inGame(): SoundEntry[] {
    return this.all().filter((s) => !s.draft);
  }

  /** `name`, or the next free name after it when a sound of the game already has it (a draft never replaces one). */
  freeName(name: string): string {
    const taken = (n: string) => {
      const s = this.get(n);
      return !!s && !s.draft;
    };
    if (!taken(name)) return name;
    for (let i = 2; i < 100; i++) if (!this.get(`${name}${i}`)) return `${name}${i}`;
    return `${name}${Date.now().toString(36)}`;
  }

  /** audio/CREDITS.md for the imported sounds (removed when there are none left). */
  writeCredits(): string {
    const path = join(this.root, AUDIO_CREDITS_REL);
    const text = creditsMarkdown(this.all());
    if (!text) {
      if (existsSync(path)) rmSync(path);
      return '';
    }
    mkdirSync(this.dir(), { recursive: true });
    writeFileSync(path, text, 'utf8');
    return text;
  }

  writeBuilder(): string {
    const all = this.inGame();
    const path = join(this.root, AUDIO_BUILDER_REL);
    if (!all.length) {
      if (existsSync(path)) rmSync(path);
      return '';
    }
    const code = audioBuilder(all);
    mkdirSync(join(this.root, 'world'), { recursive: true });
    writeFileSync(path, code, 'utf8');
    return code;
  }

  /**
   * Which of the game's sounds its code plays, and from which scripts (project-relative): a script calls
   * an audio/sound/sfx/music function with the name (Audio.play("Hit"), Sfx:Play("Hit")) or a function whose
   * own name says it plays one (Style.sfx("UI_Click"), Feedback.loop("TreadRumble"), playSound("Hit")),
   * builds the name from a quoted prefix in such a call or in a script requiring ShurikenAudio
   * ("Fire_" .. weapon: every Fire_* sound), names it while requiring ShurikenAudio (a string, or a table
   * key: Hit = { volume = 1 }), or uses its asset id. Drafts are never in use.
   */
  usage(syncMap: SyncMap | undefined): Map<string, string[]> {
    const out = new Map<string, string[]>();
    const sounds = this.inGame();
    if (!sounds.length) return out;
    const map = syncMap && Object.keys(syncMap).length ? syncMap : DEFAULT_SYNC_MAP;
    const files: string[] = [];
    const walk = (dir: string, depth: number) => {
      if (depth > 12 || files.length > 4000 || !existsSync(dir)) return;
      for (const e of readdirSync(dir, { withFileTypes: true })) {
        if (e.name.startsWith('.') || e.name === 'node_modules' || e.name === 'Packages') continue;
        const f = join(dir, e.name);
        if (e.isDirectory()) walk(f, depth + 1);
        else if (/\.luau?$/.test(e.name) && e.name !== 'ShurikenAudio.luau') files.push(f);
      }
    };
    for (const d of new Set(Object.keys(map))) walk(join(this.root, d), 0);
    const esc = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const tests = sounds.map((s) => {
      const q = `["']${esc(s.name)}["']`;
      const ids = [s.assetId, ...(s.variations ?? []).map((v) => v.assetId)].filter((x): x is string => !!x);
      return {
        name: s.name,
        lower: s.name.toLowerCase(),
        ids,
        call: new RegExp(`\\w*(?:audio|sound|sfx|music)\\w*\\s*[.:]\\s*\\w+\\s*\\(\\s*${q}`, 'i'),
        callee: new RegExp(`${PLAYS}\\s*\\(\\s*${q}`, 'i'),
        quoted: new RegExp(q),
        key: new RegExp(`(?:^|[{,;])[ \\t]*${esc(s.name)}\\s*=(?!=)`, 'm'),
        id: ids.length ? new RegExp(`\\b(?:${ids.map(esc).join('|')})\\b`) : null,
      };
    });
    // A name put together in the code: a quoted prefix joined to something ("Fire_" .. weapon).
    const prefixed = (src: string, anywhere: boolean): string[] => {
      const rx = anywhere ? /["']([\w.-]{2,})["']\s*\.\./g : new RegExp(`${PLAYS}\\s*\\(\\s*["']([\\w.-]{2,})["']\\s*\\.\\.`, 'gi');
      return [...src.matchAll(rx)].map((m) => m[1]!);
    };
    // What a file plays is remembered until the file or the sound list changes: the Audio page asks on every
    // refresh, and reading every script against every sound took 370-470 ms of the core's one thread (which also
    // runs every agent's tool calls) in a game with 44 sounds.
    const soundsKey = sounds.map((x) => `${x.name}:${x.assetId ?? ''}:${(x.variations ?? []).map((v) => v.assetId ?? '').join(',')}`).join('|');
    for (const f of files) {
      let stamp: string;
      try {
        const st = statSync(f);
        stamp = `${st.mtimeMs}:${st.size}`;
      } catch {
        continue;
      }
      const rel = relative(this.root, f).replace(/\\/g, '/');
      const known = USAGE_CACHE.get(f);
      let names: string[];
      if (known && known.stamp === stamp && known.sounds === soundsKey) names = known.names;
      else {
        let src: string;
        try {
          src = readFileSync(f, 'utf8');
        } catch {
          continue;
        }
        const requires = src.includes('ShurikenAudio');
        const prefixes = prefixed(src, requires);
        const byPrefix = (name: string) => prefixes.some((p) => name.length > p.length && name.startsWith(p));
        // Every test but the id's needs the name in the file (the calls' in any case): a file that doesn't contain
        // it skips them. Testing every sound's patterns against every script took 9 s of the core's one thread on
        // its first read in a game with 300 sounds, and every request to the core waited behind it.
        const lower = src.toLowerCase();
        names = tests
          .filter((t) => (lower.includes(t.lower) && (t.call.test(src) || t.callee.test(src) || (requires && (t.quoted.test(src) || t.key.test(src))))) || byPrefix(t.name) || (!!t.id && t.ids.some((i) => src.includes(i)) && t.id.test(src)))
          .map((t) => t.name);
        if (USAGE_CACHE.size > 8000) USAGE_CACHE.clear();
        USAGE_CACHE.set(f, { stamp, sounds: soundsKey, names });
      }
      for (const n of names) out.set(n, [...(out.get(n) ?? []), rel]);
    }
    return out;
  }

  static runtimeLocation(syncMap: SyncMap | undefined): { file: string; requirePath: string } {
    const map = syncMap && Object.keys(syncMap).length ? syncMap : DEFAULT_SYNC_MAP;
    const shared = Object.entries(map).find(([, inst]) => inst === 'ReplicatedStorage' || inst.startsWith('ReplicatedStorage/')) ?? ['src/Shared', 'ReplicatedStorage/Shared'];
    const segs = shared[1].split('/').slice(1);
    return {
      file: `${shared[0].replace(/\/$/, '')}/ShurikenAudio.luau`,
      requirePath: ['game.ReplicatedStorage', ...segs.map((s) => (/^[A-Za-z_]\w*$/.test(s) ? s : `[${JSON.stringify(s)}]`)), 'ShurikenAudio'].join('.').replace(/\.\[/g, '['),
    };
  }

  ensureRuntime(syncMap: SyncMap | undefined): { file: string; requirePath: string; written: boolean } {
    const loc = SoundLibrary.runtimeLocation(syncMap);
    const path = join(this.root, loc.file);
    if (existsSync(path)) {
      const m = RUNTIME_MARKER.exec(readFileSync(path, 'utf8'));
      if (!m || Number(m[1]) >= AUDIO_RUNTIME_VERSION) return { ...loc, written: false };
    }
    mkdirSync(join(path, '..'), { recursive: true });
    writeFileSync(path, AUDIO_RUNTIME_MODULE, 'utf8');
    return { ...loc, written: true };
  }
}
