  type Def = { handler: (a: { args: unknown; caller: unknown; signal?: AbortSignal }) => Promise<{ isError?: boolean; content: Array<{ type: string; text?: string }> }> };
  /** The Storefront's tools on their own, with the push's real "put it in the game" and an optional judge. */
  function tools(root: string, extra: { judge?: (prompt: string, images: unknown[]) => Promise<unknown> } = {}) {
    const defs = new Map<string, Def>();
    const ctx = { root, summary: { id: 'p', name: 'Sound Wars', description: 'Speakers fight it out' }, extras: () => ({}), audit: { event: () => {} } };
    const sp = new StorePush({ cloud: {} as never, studio: { connected: false } as never, bus: { emit: () => {} } as never, log: { warn: () => {} } as never });
    registerStorefrontTools({ register: (d: Def & { name: string }) => defs.set(d.name, d) } as never, {
      project: () => ctx as never,
      studio: {} as never,
      bus: { emit: () => {} } as never,
      prefs: () => ({ monetization: true, copy: true }),
      resourcesDir: null,
      apply: (p) => sp.apply(p),
      ...(extra.judge ? { judge: extra.judge as never } : {}),
    });
    const call = (name: string, args: unknown, caller: Record<string, unknown> = {}) => defs.get(name)!.handler({ args, caller: { kind: 'agent', runId: 'run_c', taskId: null, role: 'copilot-store', providerId: null, allowedTools: null, ...caller } });
    const text = (o: { content: Array<{ text?: string }> }) => o.content.map((c) => c.text ?? '').join('\n');
    return { call, text };
  }

  it("a draft turn changes the store's design, not the game's module, until the store is put in the game", async () => {
    const root = mkdtempSync(join(tmpdir(), 'shuriken-sf-draft-'));
    const { call, text } = tools(root);
    const mod = join(root, 'src/Shared/ShurikenStore.luau');
    await call('store_catalog', { style: 'cosmetic', set: [{ key: 'VIP', kind: 'pass', name: 'VIP', price: 299, benefit: 'VIP name tag' }] });
    const sf = new Storefront(root);
    const before = readFileSync(mod, 'utf8');
    expect(sf.moduleBehind()).toBe(false);
    const draft = await call('store_catalog', { set: [{ key: 'VIP', price: 399, name: 'VIP Club' }] }, { drafts: true });
    expect(text(draft)).toMatch(/A draft: the Storefront page shows it/);
    expect(readFileSync(mod, 'utf8')).toBe(before);
    expect(sf.catalog().items[0]!.price).toBe(399);
    expect(sf.moduleBehind()).toBe(true);
    await call('copy_write', { items: [{ key: 'VIP', name: 'VIP Lounge' }] }, { drafts: true });
    expect(readFileSync(mod, 'utf8')).toBe(before);
    const put = await call('store_module', {});
    expect(text(put)).toMatch(/ShurikenStore\.luau written; it reaches Studio with the next sync/);
    expect(readFileSync(mod, 'utf8')).toContain('price = 399, name = "VIP Lounge"');
    expect(sf.moduleBehind()).toBe(false);
  });

  it('a judge who did not make them eliminates the thumbnails down to one', async () => {
    const root = mkdtempSync(join(tmpdir(), 'shuriken-sf-judge-'));
    const seen: number[] = [];
    const { call, text } = tools(root, {
      judge: async (_prompt, images) => {
        seen.push(images.length);
        return { rounds: [{ out: 'C', why: 'too dark to read small' }, { out: 'A', why: 'two subjects fight' }], winner: 'B', why: 'one hero, readable at a glance' };
      },
    });
    for (const [n, c] of [['a', '#ff0000'], ['b', '#00ff00'], ['c', '#0000ff']]) await call('thumb_compose', { name: n, size: 'thumbnail', screens: [{ name: 'T', kids: [{ name: 'Bg', cls: 'Frame', size: [1, 0, 1, 0], bg: c }] }] });
    const r = await call('thumb_pick', {});
    expect(seen).toEqual([3]);
    expect(text(r)).toMatch(/Winner: b\. one hero[\s\S]*1\. c: too dark[\s\S]*2\. a: two subjects/);
    expect(readArt(root).pick).toMatchObject({ winner: 'b', rounds: [{ out: 'c' }, { out: 'a' }], among: ['a', 'b', 'c'] });
  });
