/**
 * The Storefront (1.15): a store designed for the game's genre and built into it (ShurikenStore), its copy and its
 * pictures, each by its own expert; on Roblox only on the user's word.
 */
const item = (over: Partial<StoreItem> = {}): StoreItem => ({ key: 'VIP', kind: 'pass', name: 'VIP', description: 'A golden name tag and a VIP lounge.', price: 199, benefit: 'VIP name tag and lounge access', ...over });
const catalog = (items: StoreItem[], style: StoreCatalog['style'] = 'fair'): StoreCatalog => ({ style, why: '', items, updatedAt: '' });

describe('the catalog and the copy are checked', () => {
  it('refuses what Roblox refuses and what points off Roblox', () => {
    expect(checkCatalog(catalog([item()])).errors).toEqual([]);
    const bad = checkCatalog(catalog([item({ key: '1x', price: 0, name: 'x'.repeat(STORE_LIMITS.name + 1), benefit: '' }), item({ key: 'Coins', kind: 'product', name: 'Join discord.gg for coins' })])).errors.join('\n');
    expect(bad).toMatch(/1x: key must be a code name/);
    expect(bad).toMatch(/name is 51 characters/);
    expect(bad).toMatch(/price must be a whole number/);
    expect(bad).toMatch(/benefit/);
    expect(bad).toMatch(/Coins: nothing may point players off Roblox/);
    expect(checkCatalog(catalog([item(), item()])).errors.join()).toMatch(/two items share this key/);
  });

  it('a cosmetic store points out an item that sells an advantage', () => {
    const w = checkCatalog(catalog([item({ key: 'Speed', name: '2x Speed', benefit: 'moves faster' }), item({ key: 'GoldSkin', name: 'Gold Skin', benefit: 'a gold paint on every unit' })], 'cosmetic')).warnings;
    expect(w).toHaveLength(1);
    expect(w[0]).toMatch(/Speed: the store is cosmetic-only/);
  });

  it('the title and description keep to their limits', () => {
    expect(checkCopy('title', 'Sound Wars').errors).toEqual([]);
    expect(checkCopy('title', 'x'.repeat(STORE_LIMITS.title + 1)).errors[0]).toMatch(/Roblox allows 50/);
    expect(checkCopy('description', 'Follow us on youtube.com/x').errors[0]).toMatch(/off Roblox/);
    expect(checkCopy('description', 'Short.').warnings[0]).toMatch(/under 150 characters/);
  });

  it("an item's status follows what was pushed", () => {
    const i = item();
    expect(itemStatus(i)).toBe('draft');
    i.roblox = { id: 9, pushedAt: '', hash: itemHash(i), forSale: true };
    expect(itemStatus(i)).toBe('live');
    i.price = 249;
    expect(itemStatus(i)).toBe('changed');
    i.roblox.forSale = false;
    expect(itemStatus(i)).toBe('offsale');
  });
});

